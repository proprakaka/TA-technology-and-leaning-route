//=========================================================
// 第07章 C# 变量 (Variables)
//=========================================================
//“变量”就是一个有名字的内存存储单元，程序通过它来保存和读取数据。

using System;

namespace VariablesTeaching
{
    class Program
    {
        static void Main()
        {
            //-----------------------------------------------------
            // 1. 声明变量：先写"类型"，再写“变量名”。
            //    语法：  类型 变量名;
            //-----------------------------------------------------
            int age;          // 声明了一个 int 类型的变量 age，但还没有赋值
            double salary;    // 声明了一个 double 类型的变量 salary

            //-----------------------------------------------------
            // 2. 初始化：在声明时直接给一个值。
            //    语法：  类型 变量名 = 值;
            //-----------------------------------------------------
            int count = 3;              // 声明并初始化为 3
            string name = "runoob";     // 字符串变量
            double pi = 3.14159;        // 双精度小数

            //-----------------------------------------------------
            // 3. 同时声明多个同类型变量：用逗号隔开。
            //-----------------------------------------------------
            int x, y, z;              // 一次声明三个 int 变量
            x = 1; y = 2; z = 3;      // 再逐个赋值（同类型多个赋值用分号隔开）

            //-----------------------------------------------------
            // 4. 类型推断 var：让编译器根据“初始值”自动推导变量类型。
            //    注意：var 仍然有强类型，只是省略了书写；必须初始化后才能用。
            //-----------------------------------------------------
            var message = "我是一个字符串";   // 编译器推断为 string
            var number = 42;                 // 编译器推断为 int
            //message = 42;                  // 错误！var 一旦确定类型就不能再存别的类型

            //-----------------------------------------------------
            // 5. 从键盘读取输入：Console.ReadLine() 读到的永远是“字符串”，
            //    需要转成想要的类型（见第06章的 Parse/TryParse）。
            //-----------------------------------------------------
            Console.WriteLine("请输入你的名字：");
            string userName = Console.ReadLine();          // 读一行字符串
            Console.WriteLine("你好，{0}！", userName);

            Console.WriteLine("请输入你的年龄：");
            string ageText = Console.ReadLine();           // 用户输入得到的是字符串
            int userAge = int.Parse(ageText);              // 把字符串转成 int
            Console.WriteLine("你输入的年龄是：{0}", userAge);

            //-----------------------------------------------------
            // 6. 输出：Console.WriteLine 用 {0}{1}... 占位符依次填入后面的值。
            //    {0} 对应第一个值，{1} 对应第二个值，依此类推。
            //-----------------------------------------------------
            Console.WriteLine("count={0}, name={1}, pi={2}, x+y+z={3}",
                              count,        name,        pi,        x + y + z);

            Console.ReadKey();
        }
    }
}

/*
【补充：变量命名规则（C# 标识符规则）】
  · 只能由字母、数字、下划线组成，且不能以数字开头；
  · 区分大小写（Name 和 name 是两个不同变量）；
  · 不能使用关键字（如 int、class、namespace 等）作为变量名；
  · 约定：变量名通常用小写开头的"驼峰命名"，如 userName、myAge。

【变量的“作用域”】
  变量只在它被声明的那个"代码块(大括号 {} 内部)"里有效，出了括号就失效了。
  这个在后面的方法、类章节会进一步体会。
*/