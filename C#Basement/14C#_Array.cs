//=========================================================
// 第15章 C# 数组 (Array)
//=========================================================
//数组：用来一次性保存“同类型”的多个数据，通过下标(索引)访问，下标从 0 开始。

using System;

namespace ArrayTeaching
{
    class Program
    {
        static void Main()
        {
            //-----------------------------------------------------
            // 1. 一维数组：三种声明/初始化方式
            //-----------------------------------------------------
            int[] arr1 = new int[5];            // 方式一：先按长度创建，默认都是 0
            int[] arr2 = { 10, 20, 30, 40 };    // 方式二：声明时直接给初值
            int[] arr3 = new int[3] { 1, 2, 3 }; // 方式三：指定长度并给初值

            arr1[0] = 100;   // 给下标 0 的位置赋值（下标从 0 数起）
            Console.WriteLine("arr1[0] = {0}", arr1[0]);

            //-----------------------------------------------------
            // 2. 用 for 循环遍历数组：用 Length 属性拿到数组元素个数。
            //-----------------------------------------------------
            Console.WriteLine("arr2 内容：");
            for (int i = 0; i < arr2.Length; i++)
            {
                Console.WriteLine("  arr2[{0}] = {1}", i, arr2[i]);
            }

            //用 foreach 遍历数组（更简洁，第11章已介绍）
            Console.WriteLine("arr3 内容(foreach)：");
            foreach (int v in arr3)
            {
                Console.WriteLine("  " + v);
            }

            //-----------------------------------------------------
            // 3. 二维数组（矩形数组）：类型[,] 变量 = new 类型[行, 列];
            //-----------------------------------------------------
            int[,] matrix = new int[2, 3]
            {
                { 1, 2, 3 },
                { 4, 5, 6 }
            };
            Console.WriteLine("matrix[1, 2] = {0}", matrix[1, 2]);   // 第2行第3列 = 6

            //-----------------------------------------------------
            // 4. 交错数组（数组的数组）：每一行长度可以不同。
            //    定义时用 [][]，内层再分别 new。
            //-----------------------------------------------------
            int[][] jagged = new int[2][];       // 外层是"两个子数组"
            jagged[0] = new int[] { 1, 2, 3 };    // 第一行 3 个元素
            jagged[1] = new int[] { 4, 5 };       // 第二行 2 个元素
            Console.WriteLine("jagged[1][0] = {0}", jagged[1][0]);   // 4

            //-----------------------------------------------------
            // 5. 常用的 System.Array 静态方法（不用 new 就能用的工具方法）
            //-----------------------------------------------------
            int[] nums = { 5, 2, 9, 1, 7 };
            Array.Sort(nums);       // 从小到大排序（原地修改）
            Array.Reverse(nums);    // 反转（原地修改）
            Console.WriteLine("排序并反转后：");
            foreach (int v in nums) Console.Write(v + " ");
            Console.WriteLine();

            Console.ReadKey();
        }
    }
}

/*
【小结】
  · 数组是固定长度、同类型的集合，下标从 0 开始；
  · 一维：int[] a = {1,2,3};  二维(矩形)：int[,]；交错：int[][]；
  · Length 属性 = 元素个数，常用 for/foreach 遍历；
  · Array.Sort 排序、Array.Reverse 反转是常用工具方法。
*/