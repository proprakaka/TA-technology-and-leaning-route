//=========================================================
// 第11章 C# 循环（Loop）
//=========================================================
//循环：让一段代码重复执行多次。
//主要有：while / for / do-while / foreach，以及控制关键字 break / continue / goto。

using System;

namespace LoopTeaching
{
    class Program
    {
        static void Main()
        {
            //-----------------------------------------------------
            // 1. while 循环：先判断条件，成立才执行；不成立一次都不执行。
            //-----------------------------------------------------
            int i = 0;
            while (i < 5)              // 条件 i < 5
            {
                Console.WriteLine("while 循环 i = {0}", i);
                i++;                   // 一定要让条件有朝一日不成立，否则会死循环
            }

            Console.WriteLine(new string('-', 30));

            //-----------------------------------------------------
            // 2. for 循环：把“初始化、条件、每次迭代后操作”写在一行里。
            //    语法：for(初始化; 条件; 迭代) { ... }
            //-----------------------------------------------------
            for (int j = 0; j < 5; j++)
            {
                Console.WriteLine("for 循环 j = {0}", j);
            }

            Console.WriteLine(new string('-', 30));

            //-----------------------------------------------------
            // 3. do-while 循环：先执行一次，再判断条件。至少执行一次。
            //-----------------------------------------------------
            int k = 0;
            do
            {
                Console.WriteLine("do-while 循环 k = {0}", k);
                k++;
            } while (k < 3);

            Console.WriteLine(new string('-', 30));

            //-----------------------------------------------------
            // 4. foreach 循环：专门用来“遍历集合/数组的每一个元素”。
            //    语法：foreach(元素类型 变量名 in 集合) { ... }
            //-----------------------------------------------------
            int[] numbers = { 10, 20, 30, 40 };   // 数组，第15章会详细讲
            foreach (int n in numbers)
            {
                Console.WriteLine("foreach 元素 n = {0}", n);
            }

            Console.WriteLine(new string('-', 30));

            //-----------------------------------------------------
            // 5. 循环控制关键字
            //    break：立即跳出(终止)整个循环；
            //    continue：跳过本次剩余语句，直接进入下一次循环。
            //-----------------------------------------------------
            for (int m = 0; m < 10; m++)
            {
                if (m == 3) break;        // 到 3 就退出循环
                Console.WriteLine("break 示例：m = {0}", m);
            }

            for (int p = 0; p < 5; p++)
            {
                if (p == 2) continue;     // 跳过 p==2 这一次
                Console.WriteLine("continue 示例：p = {0}", p);
            }

            Console.ReadKey();
        }
    }
}

/*
【小结】
  · while：先判断后执行，可能一次都不执行；
  · for：把初始化/条件/迭代集中在一起，最常用；
  · do-while：先执行后判断，至少执行一次；
  · foreach：专门遍历数组/集合中的每个元素；
  · break：终止循环；continue：跳过本次进入下一次；
  · 无限循环：如 while(true) 或 for(;;)，需配合 break 退出（有需要时再用）。
*/