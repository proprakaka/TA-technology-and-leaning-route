# -*- coding: utf-8 -*-
"""
第 03 章：运算符和表达式
========================
"表达式（expression）" = 由值、变量、运算符组合成的、能算出结果的东西。
例：1 + 2、a * 3、x > 5、not flag 都是表达式。

运算符（operator）就是表达式中"做动作"的符号。本章按类别逐个击破：
  1. 算术  2. 比较  3. 赋值  4. 位  5. 逻辑  6. 成员  7. 身份  8. 优先级
================================================================
"""

# =====================================================================
# 一、算术运算符（对数字做数学运算）
# =====================================================================
a, b = 10, 3      # 连续赋值：a=10, b=3（这种写法 Python 特有，后面会用）
print("加法 + ：", a + b)     # 13
print("减法 - ：", a - b)     # 7
print("乘法 * ：", a * b)     # 30
print("除法 / ：", a / b)     # 3.3333... 注意：/ 永远得到 float
print("整除 // ：", a // b)   # 3  去掉小数部分、向下取整
print("取余 % ：", a % b)     # 1  取除法的余数
print("幂 ** ：", a ** b)     # 1000  10 的 3 次方

"""
【易混点】两个"除"别搞混：
  - /  是真除法，结果一定是 float，例如 10/2 也得到 5.0。
  - // 是整除（地板除 floor division），结果是 int（两者都是 int 时），向下取整。

【易错点】负数的 // 和 % 结果看起来"反直觉"，因为 Python 是"向下取整"：
"""
print(-7 // 3)      # -3  （-2.333 向下取整到 -3，不是 -2！）
print(-7 % 3)       # 2   （Python 保证：被除数 = 商*除数 + 余数，即 -7 = -3*3 + 2）
print(7 // -3)      # -3
print(7 % -3)       # -2

# =====================================================================
# 二、比较运算符（结果一定是 True 或 False）
# =====================================================================
x, y = 5, 8
print("等于 == ：", x == y)      # False
print("不等于 != ：", x != y)    # True
print("大于 > ：", x > y)        # False
print("小于 < ：", x < y)        # True
print("大于等于 >= ：", x >= y)  # False
print("小于等于 <= ：", x <= y)  # True

"""
【易错点】= 和 == 天差地别：
  - =  是赋值（把右边交给左边）。
  - == 是比较（问两边是否相等）。
  新手写 `if x = 5:` 会报错，正确是 `if x == 5:`。
"""

# 比较可以连写（链式比较，数学书里的 a < b < c 这样写是合法的）：
print(1 < 3 < 5)    # True，等价于 1<3 且 3<5

# =====================================================================
# 三、赋值运算符（给变量绑定值）
# =====================================================================
n = 10             # 基本赋值
n += 5             # 等价 n = n + 5
print("+= 后：", n)          # 15
n -= 3             # n = n - 3
print("-= 后：", n)          # 12
n *= 2             # n = n * 2
print("*= 后：", n)          # 24
n /= 4             # n = n / 4
print("/= 后：", n)          # 6.0
n //= 2            # 整除赋值
print("//= 后：", n)         # 3.0
n %= 2             # 取余赋值
print("%= 后：", n)          # 1.0
n **= 3            # 幂赋值
print("**= 后：", n)         # 1.0

"""
【原理】n += 5 只是 n = n + 5 的简写（语法糖），让代码更短。
  对可变对象（如列表），+= 还可能调用该对象的"就地修改"方法，见第 05 章。
"""

# =====================================================================
# 四、位运算符（直接对二进制的每一位操作）
# =====================================================================
"""
【原理】位运算前，先回忆二进制：
  十进制 5 = 二进制 0101
  十进制 3 = 二进制 0011
  位运算就是"竖着对齐，一位一位算"，这是最贴近硬件层的运算。
"""
p, q = 5, 3      # 0101 和 0011
print("按位与 & ：", p & q)    # 0001 = 1   （两位都是1才得1）
print("按位或 | ：", p | q)    # 0111 = 7   （两位有1就得1）
print("按位异或 ^ ：", p ^ q)  # 0110 = 6   （两位不同得1）
print("按位取反 ~ ：", ~p)     # -6（见下方说明，含符号位）
print("左移 << ：", p << 1)    # 1010 = 10  （整体左移1位，相当于 *2）
print("右移 >> ：", p >> 1)    # 0010 = 2   （整体右移1位，相当于 //2）

"""
【易错点】~p 为什么是 -6？因为 Python 整数用"补码"表示，~ 会把所有位翻转
  （包括符号位），结果等于 -(p+1)。
  不用死记，知道 ~x = -(x+1) 即可。位运算日常用得不多，先建立概念即可。
"""

# aspect：左移/右移与乘除 2 的关系
print("左移1位等于乘2：", 5 << 1, "==", 5 * 2)
print("右移1位等于整除2：", 5 >> 1, "==", 5 // 2)

# =====================================================================
# 五、逻辑运算符（组合多个真假条件）
# =====================================================================
"""
and / or / not 操作的是"真假值"，并且是"短路"求值（见【原理】）。
"""
t, f = True, False
print("与 and：", t and f)    # False（两边都真才真）
print("或 or：", t or f)      # True （有一边真就真）
print("非 not：", not t)      # False（真变假、假变真）

"""
【原理】"短路求值"（short-circuit）：
  - A and B：如果 A 已经是 False，就**不计算 B**，直接返回 False。
  - A or B ：如果 A 已经是 True，就**不计算 B**，直接返回 True。
  这不仅能省计算，还能用来做"安全"判断（先判断前面的条件，避免后面的报错）。

  实际上 and/or 返回的是"参与运算的那个值"，不一定是 True/False：
"""
print(0 and 10)         # 0    （0 为假，短路，返回 0）
print(3 and 10)         # 10   （3 为真，还得看 10，返回 10）
print(0 or "默认值")    # '默认值'（0 为假，看右边）
print("hello" or 10)    # 'hello'（非空字符串为真，短路，返回它自己）

"""
【易错点】上面这个"返回参与值"的特性，常用来写默认值：
      result = 用户提供的值 or 默认值
  但要注意：如果"用户提供的值"可能是 0 或空字符串（它们为假），
  会被误当成"没提供"，从而错用默认值。这是常见坑，务必理解真假值规则。
"""

# =====================================================================
# 六、成员运算符 in / not in（判断"在不在里面"）
# =====================================================================
"""
in 判断某个元素是否存在于一个"容器"（字符串、列表、元组、字典、集合）中。
  容器类型在后续章节详解，这里先用字符串/列表感受一下。
"""
print("a" in "apple")          # True（子串/字符在字符串里）
print("z" in "apple")          # False
print(3 in [1, 2, 3])          # True（列表里有没有 3）
print(3 not in [1, 2, 3])      # False
# 字典里 in 判断的是"键"，见第 07 章。

# =====================================================================
# 七、身份运算符 is / is not（判断"是不是同一个对象"）
# =====================================================================
"""
【易混点】is 和 == 非常容易混，务必分清：
  - == 比的是"值"是否相等。
  - is 比的是"是不是同一个对象"（内存地址是否相同，等价于 id 是否相等）。
"""
m = [1, 2, 3]
k = [1, 2, 3]
print("== 比较：", m == k)       # True（内容一样）
print("is 比较：", m is k)       # False（两个不同的列表对象，地址不同）
print(id(m), id(k))              # 打印两个地址，可看到不同

# 小整数缓存会让 is 结果"偶尔为 True"，这是实现细节，不要依赖（见下方）：
small_a = 5
small_b = 5
print("小整数 is：", small_a is small_b)   # True（Python 缓存了 -5~256 的小整数）
big_a = 1000
big_b = 1000
print("大整数 is：", big_a is big_b)       # 可能是 False（未缓存，各建各的对象）

"""
【易错点】判断相等，默认用 == 就好；is 只在少数场合用（例如判断 x is None）。
  不要写 `if x == True:`（多余），也不要依赖小整数缓存的 is 结果。
"""

# =====================================================================
# 八、运算符优先级（先算谁后算谁）
# =====================================================================
"""
【原理】优先级从高到低（同级别从左到右，多数如此）：
  1. **                         幂（注意它右结合，见下）
  2. +x, -x, ~x                 一元正负号、按位取反
  3. *, /, //, %                乘除整除取余
  4. +, -                       加减
  5. <<, >>                     移位
  6. &                          按位与
  7. ^                          按位异或
  8. |                          按位或
  9. ==, !=, >, <, >=, <=, is, in   比较与身份成员
  10. not                       逻辑非
  11. and                       逻辑与
  12. or                        逻辑或

  记不住就加括号，括号永远最高优先级、最清晰。
"""
print(2 + 3 * 4)          # 14（先乘后加）
print((2 + 3) * 4)        # 20（括号先算）
print(2 ** 3 ** 2)        # 512，注意：** 是右结合 = 2**(3**2) = 2**9

"""
【易错点】** 是右结合：2 ** 3 ** 2 是 2 ** (3 ** 2) = 512，而不是 (2**3)**2 = 64。
  不加括号时极易看错，建议显式写括号。
"""

