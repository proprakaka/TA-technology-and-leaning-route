# =====================================================================
# 一、用列表实现"栈"（stack，后进先出 LIFO）
# =====================================================================
"""
【原理】栈就像一摞盘子：最后放上去的，最先被拿走（后进先出）。
  操作两种：压栈(push)=append，弹栈(pop)=pop()（默认弹末尾）。
"""
stack = []
stack.append("第1本")       # 压栈
stack.append("第2本")
stack.append("第3本")
print("栈顶：", stack[-1])   # 第3本（最后进的）

print(stack.pop())          # 弹栈：第3本（最后进的先出）
print(stack.pop())          # 第2本
print(stack)                # ['第1本']

# =====================================================================
# 二、用 collections.deque 实现"队列"（queue，先进先出 FIFO）
# =====================================================================
"""
【原理】队列像排队买票：先来的先被服务（先进先出）。
  列表做队列的话，在头部 pop(0) 很慢（后面所有元素都要前移）；
  collections.deque（双端队列）在两端的增删都是 O(1)，效率高。
"""
from collections import deque

q = deque()
q.append("顾客1")           # 入队（队尾）
q.append("顾客2")
q.append("顾客3")

print(q.popleft())          # 出队（队首）：顾客1（先进的先出）
print(q)                    # deque(['顾客2', '顾客3'])

# =====================================================================
# 三、嵌套结构：列表套列表、字典套字典
# =====================================================================
# 二维列表（矩阵）：
matrix = [
    [1, 2, 3],
    [4, 5, 6],
    [7, 8, 9],
]
print(matrix[1][2])         # 6（第 2 行第 3 列）

# 字典套列表：
students = {
    "1班": ["小明", "小红"],
    "2班": ["小刚", "小丽"],
}
print(students["1班"][0])   # 小明

# 列表套字典（常见：记录列表）：
records = [
    {"name": "小明", "age": 20},
    {"name": "小红", "age": 18},
]
print(records[0]["name"])   # 小明

# 遍历二维列表：
for row in matrix:
    for item in row:
        print(item, end=" ")   # 1 2 3 4 5 6 7 8 9
print()

# =====================================================================
# 四、del 语句：删除对象/元素/切片（终于正式讲它）
# =====================================================================
"""
del 是关键字，作用：删除"引用"，让某个名字不再指向对象；也能按索引/切片删。
  若对象没有其他引用了，会被垃圾回收（第 02 章提过 GC）。
"""
x = [10, 20, 30, 40]
del x[0]               # 删下标 0
print(x)               # [20, 30, 40]
del x[1:3]             # 删切片
print(x)               # [20]

y = 5
del y                  # 删除变量名 y 本身
# print(y)             # 报错：NameError，y 已经不存在了

"""
【易混点】del 和 pop/remove 的区别：
  - del 是语句，按"索引/切片/名字"删，不返回被删值。
  - list.pop(i) 是方法，按索引删并返回该值。
  - list.remove(v) 是方法，按"值"删第一个匹配项。
"""

# =====================================================================
# 五、排序进阶：用 key 定制排序规则
# =====================================================================
words = ["banana", "apple", "cherry", "kiwi"]
# 按长度排序（key 指定：用什么标准来比大小）
print(sorted(words, key=len))          # ['kiwi', 'apple', 'banana', 'cherry']

# 按最后一个字符排序：
print(sorted(words, key=lambda w: w[-1]))

# 对字典列表按某个字段排序（很实用）：
people = [
    {"name": "小明", "age": 30},
    {"name": "小红", "age": 18},
    {"name": "小刚", "age": 25},
]
by_age = sorted(people, key=lambda p: p["age"])
print(by_age)
# 降序：
print(sorted(people, key=lambda p: p["age"], reverse=True))

# 多级排序：先按 a，再按 b（用元组做 key 即可）：
pairs = [(1, 3), (1, 1), (2, 2)]
print(sorted(pairs, key=lambda t: (t[0], t[1])))   # 先按第一个、再按第二个

# =====================================================================
# 六、zip：把多个序列"打包"成一对一对
# =====================================================================
names = ["小明", "小红", "小刚"]
scores = [90, 80, 70]
for name, score in zip(names, scores):
    print(name, score)          # 小明 90 / 小红 80 / 小刚 70

print(dict(zip(names, scores)))  # {'小明':90, '小红':80, '小刚':70}（快速造字典）

# =====================================================================
# 七、enumerate：带下标遍历（第 10 章见过，这里总结用法）
# =====================================================================
for i, v in enumerate(["a", "b", "c"], start=1):   # start=1 让下标从 1 开始
    print(i, v)

