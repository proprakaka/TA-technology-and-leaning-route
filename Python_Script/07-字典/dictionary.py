# -*- coding: utf-8 -*-
"""
第 07 章：字典 dict —— 用"键"查"值"的映射结构
================================================
到上一章为止，我们存数据都是"按顺序排一队"（列表/元组）。
字典不一样：它存的是"键(key) → 值(value)"的对应关系。
就像查字典：给定一个字（键），查到它的解释（值）。

字典是无序的（Python 3.7 起实际保留插入顺序，但语义上应把它当"映射"用），
  靠键来取东西，而不是靠位置下标。
================================================================
"""

# =====================================================================
# 一、创建字典
# =====================================================================
empty = {}                       # 空字典（注意：空的花括号是字典，不是集合！）
person = {"name": "小明", "age": 20, "city": "北京"}
print(empty, person)

# dict() 构造函数：
print(dict(name="小红", age=18))    # 用关键字参数创建，键会自动变成字符串
print(dict([("a", 1), ("b", 2)]))   # 用"二元组列表"创建

# =====================================================================
# 二、取值（靠键，不是靠下标）
# =====================================================================
person = {"name": "小明", "age": 20}
print(person["name"])          # '小明'

# .get()：取不到时返回默认值（或 None），不报错
print(person.get("name"))      # '小明'
print(person.get("height"))    # None（没有这个键，不报错）
print(person.get("height", "未知"))   # 提供默认值

"""
【易混点】person["height"] 和 person.get("height") 的区别：
  - 用 [键] 直接取：键不存在会抛 KeyError（程序中断）。
  - 用 .get(键, 默认值)：键不存在返回默认值，更安全。
  新手推荐先用 .get 熟悉字典。
"""

# =====================================================================
# 三、增、改、删
# =====================================================================
d = {}
d["name"] = "小李"         # 增加一个键值对（键不存在即新增）
print(d)                   # {'name': '小李'}

d["name"] = "小王"         # 键已存在，则是"修改"其中的值
print(d)                   # {'name': '小王'}

d["age"] = 25
print(d)                   # {'name': '小王', 'age': 25}

d.pop("age")               # 删除键 age（并返回它的值）
print(d)                   # {'name': '小王'}

# del d["name"]            # 也能用 del 删除键（第 16 章讲 del）
# d.clear()                # 清空整个字典

# =====================================================================
# 四、遍历字典
# =====================================================================
info = {"a": 1, "b": 2, "c": 3}
for k in info:                   # 默认遍历"键"
    print(k)                     # a b c（按插入顺序）

for k in info.keys():            # 显式遍历键（等价于上面）
    print(k)

for v in info.values():          # 遍历值
    print(v)

for k, v in info.items():        # 同时遍历键和值（最常用）
    print(f"{k} -> {v}")

# =====================================================================
# 五、检查键是否存在
# =====================================================================
print("a" in info)         # True（判断键在不在）
print("x" in info)         # False
print(1 in info)           # False（注意：1 是值，不是键）

# =====================================================================
# 六、键的要求：必须是"可哈希"的（不可变对象）
# =====================================================================
"""
【原理】为什么字典查得那么快？因为它内部用"哈希表(hash table)"。
  每个键会先算出一个"哈希值"（一个整数摘要），再据此定位存储位置。
  因此键必须"可哈希(hashable)"，而可哈希的前提是"不可变"。

  - 可作为键：字符串、数字、元组（只要元组里全是不可变元素）。
  - 不可作为键：列表、字典、集合（可变对象，哈希值会变）。
"""
hash("key")              # 字符串可哈希
hash((1, 2))             # 元组可哈希
# hash([1, 2])           # 报错！列表不可哈希，不能拿 list 当键

# 所以：
valid = {("北京", "上海"): 1200}   # 元组作键，OK
print(valid[("北京", "上海")])

# 但下面这行会报错（list 不可哈希），注释掉：
# invalid = {[1, 2]: "x"}   # TypeError: unhashable type: 'list'

"""
【易混点】"可哈希"= hash() 能算、且哈希值在生命周期内不变。
  集合（第 08 章）和字典一样，也只接受可哈希元素。
  所以"列表不能放进集合 / 不能当字典键"，但元组可以。
"""

# =====================================================================
# 七、字典推导式（预告第 11 章，先露个脸）
# =====================================================================
squares = {x: x * x for x in range(5)}
print(squares)           # {0: 0, 1: 1, 2: 4, 3: 9, 4: 16}

# =====================================================================
# 本章小结 + 预告
# =====================================================================
"""
小结：
  1. 字典是"键→值"映射，靠键取值，不是靠下标。
  2. [键] 取值不存在会 KeyError，.get() 更安全。
  3. 遍历用 .items() 拿键值对。
  4. 键必须可哈希（不可变），列表/字典/集合不能作键，元组可以。

预告：下一章讲**集合 set**——去重、交集、并集、差集，它和字典同源
  （底层都靠哈希表），所以同样要求元素可哈希。
"""