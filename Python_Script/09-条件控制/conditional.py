# -*- coding: utf-8 -*-
"""
第 09 章：条件控制 if / elif / else
======================================
程序不只是从头执行到尾，它需要"做选择"：满足某条件就做 A，否则做 B。
这就是"控制流（control flow）"的第一环——条件分支。

核心：if 后面的表达式会被转成布尔值（真/假）来判定，走哪条路。
================================================================
"""

# =====================================================================
# 一、最基本的 if
# =====================================================================
age = 20
if age >= 18:              # 条件成立，才执行缩进块
    print("成年了")

# =====================================================================
# 二、if / else：二选一
# =====================================================================
score = 59
if score >= 60:
    print("及格")
else:
    print("不及格")

# =====================================================================
# 三、if / elif / else：多选一（只会命中其中一条）
# =====================================================================
score = 85
if score >= 90:
    print("优秀")
elif score >= 75:
    print("良好")          # 若上面都不满足、且 score>=75，进这里
elif score >= 60:
    print("及格")
else:
    print("不及格")

"""
【原理】if/elif/else 是"从上到下依次判断，命中第一个就停"：
  只要某个分支条件为真，就执行它并**跳过其余分支**。
  所以顺序很重要！如果把 `score >= 60` 写在最前面，90 分也会被打成"及格"。
"""

# =====================================================================
# 四、"真值"再强调：if 里可以直接放各种值
# =====================================================================
"""
if 后面的东西不一定是比较式，只要是能判"真/假"的即可。
  回忆第 02 章的真值规则：
  为假的值：0、0.0、""、[]、()、{}、set()、None；其余都为真。
"""
name = ""
if name:                    # 空字符串为假，不进入
    print("有名字")
else:
    print("名字为空")

items = [1, 2]
if items:                   # 非空列表为真，进入
    print("列表里有东西，个数", len(items))

# =====================================================================
# 五、用 and / or / not 组合条件
# =====================================================================
age = 25
has_id = True
if age >= 18 and has_id:          # 两个条件都要满足
    print("可以进入（成年且有证件）")

if age < 18 or age > 60:          # 满足一个即可
    print("享受优惠")

if not has_id:                    # 取反
    print("没有证件")

# =====================================================================
# 六、嵌套：if 里面再套 if
# =====================================================================
gender = "女"
age = 30
if age >= 18:
    if gender == "女":
        print("成年女性")
    else:
        print("成年男性")
else:
    print("未成年")

# =====================================================================
# 七、三元表达式：一行版 if/else
# =====================================================================
print("及格" if score >= 60 else "不及格")
# 语法： 值A if 条件 else 值B  —— 条件真返回 A，假返回 B

# =====================================================================
# 八、pass：占位语句（不做事）
# =====================================================================
"""
pass 是一个"空语句"，什么都不做，专门用来占位。
  写 if 时如果暂时不想写具体逻辑，又必须有缩进块，就用 pass 顶一下。
"""
if age >= 18:
    pass                # 暂时不处理，稍后补
print("程序继续")

# =====================================================================
# 本章小结 + 预告
# =====================================================================
"""
小结：
  1. if 条件成立才执行块；if/elif/else 命中即停、多选一。
  2. 条件可以是任意值，按真值规则判真假。
  3. and/or/not 组合条件；if 可嵌套；三元表达式一行搞定简单分支。
  4. pass 用来占位。

预告：下一章讲**循环**——while 和 for，让程序"重复做一件事"，
  并认识 range()、break/continue、循环嵌套这些每次写循环都要用的东西。
"""