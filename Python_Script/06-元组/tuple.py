# -*- coding: utf-8 -*-
"""
第 06 章：元组 tuple —— "不可变"的列表
========================================
元组的学名 tuple，发音 [tʌpl]（类似"塔破"），也常被读成"图普"。
它长得和列表几乎一样，唯一核心区别：**元组创建后不能修改**（不可变）。

为什么要有两种相似的东西？——因为"不可变"在工程上有独特价值。
================================================================
"""

# =====================================================================
# 一、创建元组
# =====================================================================
t1 = ()                       # 空元组
t2 = (1, 2, 3)                # 普通元组
t3 = 1, 2, 3                  # 括号其实可以省略！这也是元组
print(t1, t2, t3, type(t3))   # type 是 tuple

# 只有一个元素的元组必须加逗号（易错点！）
single_wrong = (5)            # 这是数字 5，不是元组（括号只是运算优先级）
single_right = (5,)           # 这是只有一个元素 5 的元组（逗号是关键）
print(type(single_wrong), type(single_right))   # int 和 tuple

# tuple() 可以把序列转成元组：
print(tuple([1, 2, 3]))       # (1, 2, 3)
print(tuple("abc"))           # ('a', 'b', 'c')

# =====================================================================
# 二、访问：索引、切片都支持（与列表/字符串一致）
# =====================================================================
t = (10, 20, 30, 40, 50)
print(t[0])         # 10
print(t[-1])        # 50
print(t[1:4])       # (20, 30, 40)
print(len(t))       # 5

# =====================================================================
# 三、"不可变"到底是什么不可变？
# =====================================================================
"""
【原理】元组的不变，指的是"元组这个容器本身"的元素指向不允许改变：
  不能给 t[0] 重新赋值、不能 append、不能 remove。
  但元组里装的若是一个"可变对象"（如列表），那个列表**自己**仍可变！
"""
t_mixed = (1, [2, 3], 4)
# t_mixed[0] = 10            # 报错：TypeError，元组不允许改元素
t_mixed[1].append(999)       # 合法！因为改的是里面的列表，不是元组的元素指向
print(t_mixed)               # (1, [2, 3, 999], 4)

"""
【易混点】记住一句话：元组"保证元素引用不变"，但"不保证元素内容不变"。
  所以当我们说元组"不可变"，更准确是"元组的长度和各槽位指向不能改"。
"""

# =====================================================================
# 四、元组解包（unpacking）：一次性拆开赋值
# =====================================================================
point = (3, 4)
x, y = point                 # 把元组元素分别赋给 x、y
print(x, y)                  # 3 4

# 解包也支持"一口气收下剩余部分"（用 * 收集，得到列表）：
a, *rest = (1, 2, 3, 4, 5)
print(a)            # 1
print(rest)         # [2, 3, 4, 5]（剩余的都进了 rest）

# 交换两个变量，元组解包一行搞定（其他语言常需要临时变量）：
m, n = 1, 2
m, n = n, m                 # 右边先打包成 (2, 1)，再解包
print(m, n)                 # 2 1

# =====================================================================
# 五、元组 vs 列表：什么时候用哪个？
# =====================================================================
"""
【原理】什么时候用元组？
  1. 语义上表示"一组固定搭配的数据"（如坐标、RGB 颜色、日期），
     强调"这是一个整体，不该被拆改"。
  2. 作为字典的键或集合的元素（因为元组不可变、可哈希，而列表不行）——
     见第 07、08 章。
  3. 函数返回多个值（Python 底层就是用元组打包返回的，见第 12 章）。

什么时候用列表？
  1. 数据会变（增删改）。
  2. 用同类型元素的"集合"来表示一批东西。
"""
rgb = (255, 0, 0)              # 一个颜色，用元组很合适
colors = ["red", "green"]      # 一堆会变的颜色名，用列表合适

# 元组更小的内存开销（一般情况），可用 sys.getsizeof 一窥（不必深究）：
import sys
print(sys.getsizeof((1, 2, 3)))
print(sys.getsizeof([1, 2, 3]))

# =====================================================================
# 六、常用操作小结
# =====================================================================
t = (1, 2, 3, 2)
print(t.count(2))       # 2（统计 2 出现次数）
print(t.index(3))       # 2（第一次出现 3 的下标）
print(1 in t)           # True（成员判断）
print(max(t), min(t), sum(t))   # 最大值/最小值/求和

# =====================================================================
# 本章小结 + 预告
# =====================================================================
"""
小结：
  1. 元组是不可变序列，语法用 ()（单元素要加逗号 (x,)）。
  2. 不可变指"元素指向不能改"，但嵌套的可变对象仍可变。
  3. 解包 x, y = t 很常用，还能 *rest 收集、交换变量。
  4. 列表用于"会变的数据"，元组用于"固定搭配"或需要作键/元素的场合。

预告：下一章讲**字典 dict**——用"键(key)"来查"值(value)"的映射结构，
  这也是"键必须可哈希（不可变）"这个规则首次登场。
"""