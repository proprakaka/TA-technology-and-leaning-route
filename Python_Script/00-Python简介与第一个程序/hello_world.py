# =====================================================================
# 一、先理解两个最底层的词：程序 与 解释器
# =====================================================================
"""
【原理】"程序"是什么？
  程序，就是“让计算机按顺序执行的一组指令”。
  你把每天做事的步骤写下来，就是给"人类"的指令；
  你把同样步骤写成计算机能看懂的语言，就是给"计算机"的指令——那就是程序。

  比如“泡面程序”（给人类）：
      1. 烧水
      2. 打开包装
      3. 把面放进碗里
      4. 倒入开水，等 3 分钟
      5. 开吃

  Python 程序（给计算机）本质就是用 Python 语言写的、这样的"步骤清单"。
  下面这行代码，就是一个只有 1 条指令的最小程序：
"""
print("第一条指令：在屏幕上显示这行字")

"""
【原理】解释器（interpreter）是什么？
  计算机的 CPU 只认识"机器语言"（一串 0 和 1），它看不懂我们写的
  print("...")。所以中间需要一个"翻译官"：

      你写的 .py 源代码  ──►  解释器逐行翻译并执行  ──►  屏幕上的结果

  Python 是"解释型语言"：解释器一行一行地读你的代码、翻译、立刻执行。
  对比"编译型语言"（如 C 语言）是先整体翻译成一个可执行文件，再运行。

  你安装的 Python，核心就是这个解释器。你在命令行输入 `python`，
  就是把解释器叫出来干活。
  （"环境变量 / PATH"为什么能让 `python` 命令被找到，原理见下面第 32 行起）
"""

# =====================================================================
# 二、print()：你认识的第一个"函数"
# =====================================================================
"""
print() 会在屏幕上打印（输出）一段内容。
  括号里放什么，它就打印什么。
  这里第一次出现"函数(function)"这个词——不要慌，你现在只需要知道：
      print 是一个"内置函数"，Python 官方已经帮你写好了它的实现，
      你直接"调用"它即可，格式是： 名字(要交给它的东西) 。

  【将在第 12 章详解】函数到底怎么自己定义、参数怎么传、返回值是什么。
  现在你只需学会"调用" print。
"""
print("Hello, World!")        # 打印一段文字（字符串，见第 04 章）
print(123)                    # 打印一个数字
print(1 + 2)                  # 先算 1+2，再打印结果 3
print("你好，Python")         # 中文也没问题（源码默认 UTF-8 编码，见第 01 章）

# =====================================================================
# 三、三种运行 Python 代码的方式
# =====================================================================
"""
方式 1：交互式模式（REPL）
  在命令行里直接输入 `python` 回车，会出现 >>> 提示符。
  你输入一行，解释器立刻执行一行并回显结果。适合随手试验。
  >>> 是提示符，不是让你敲进去的字符。

方式 2：脚本文件模式（我们本套文件采用的方式）
  把代码写进 .py 文件，用 `python 文件名.py` 一次性执行。
  适合写正经的程序、需要保存和复用的场合。

方式 3：集成开发环境（IDE，如 PyCharm / VS Code）
  提供自动补全、调试等便利，但底层仍然是调用解释器。
  （IDE 只是"豪华外壳"，干的活和方式 2 一样：把文件交给解释器执行。）
"""

# =====================================================================
# 四、脚本文件顶部那行 # -*- coding: utf-8 -*- 是啥？
# =====================================================================
"""
这行叫"编码声明"。Python 3 的源码**默认就是 UTF-8 编码**，其实不写也行。
它只在你想指定为其他编码时才有必要显式写出，例如：
    # -*- coding: cp-1252 -*-
会让解释器用 Windows-1252 编码来读这个文件（用于某些西欧语言字符）。

  为什么中文能正常显示？因为 UTF-8 编码能表示中文。
  【将在第 01 章详解】"编码"到底是什么、UTF-8 和 Unicode 的关系。

  写法很宽容，下面两种都等价：
    # -*- coding: utf-8 -*-
    # coding: utf-8
"""

# =====================================================================
# 五、查看你机器上的 Python 版本
# =====================================================================
"""
这不是 .py 代码，而是在命令行执行的命令（注意是命令行，不是 Python 里）：
    python -V      或      python --version
会输出类似：Python 3.12.1
版本怎么看：3 是大版本，12 是次要版本，1 是补丁版本。3.x 都叫 Python 3。

下面这段代码能在"代码内部"读取版本号，先看一眼结果即可，不用深究：
"""
import sys            # import：引入一个"模块"（工具箱），将在第 17 章详解
print(sys.version)    # 打印当前解释器的完整版本信息

# =====================================================================
# 六、关于 "Add Python to PATH" 这件事（易混点）
# =====================================================================
"""
【易混点】为什么装好 Python 后，命令行里敲 `python` 可能说"找不到"？
  因为命令行要运行一个程序，必须知道这个程序（解释器）在磁盘的哪个位置。
  操作系统维护着一张"搜索清单"，叫环境变量 PATH。
  当你在命令行敲 `python` 时，系统会去 PATH 里列出的每个文件夹里找
  一个叫 python 的可执行文件。

  安装时勾选 "Add Python to PATH"，就是把 Python 安装目录自动加进这张清单。
  （在第 19 章的 os 模块、第 21 章作用域里，你会不断和"环境/命名空间"
   这类"查找清单"的概念打照面，它们的思想是同构的。）
"""

