# -*- coding: utf-8 -*-
"""
第 10 章：循环语句 while / for
================================
循环让程序"重复执行一段代码"。
Python 有两个循环：
  1. while：只要条件为真，就一直重复（不知道要几次时用）。
  2. for  ：逐个取出序列里的元素，遍历完就停（知道要遍历谁时用）。

配套工具：
  - range()：生成一串整数，是 for 循环的好搭档。
  - break    ：提前跳出循环。
  - continue ：跳过本轮剩余代码，进入下一轮。
  - 循环嵌套：循环套循环。
================================================================
"""

# =====================================================================
# 一、while：条件为真就继续
# =====================================================================
count = 1
while count <= 3:              # 条件成立就执行块
    print("第", count, "次")
    count += 1                 # 一定要有让条件最终变假的语句，否则死循环！

print("循环结束，count =", count)

"""
【易错点】while 最常见的 bug 是"死循环"：忘了改条件变量，或条件永远为真，
  程序卡住停不下来。写 while 前先想清楚"什么条件下它会停下"。
"""

# 用 while 累加 1 到 100：
total = 0
i = 1
while i <= 100:
    total += i
    i += 1
print("1~100 的和：", total)

# =====================================================================
# 二、for：遍历序列里的每个元素
# =====================================================================
fruits = ["apple", "banana", "cherry"]
for fruit in fruits:           # fruit 依次等于每个元素
    print(fruit)

# for 遍历字符串（逐个字符）：
for ch in "hi":
    print(ch)

# for 遍历字典（默认遍历键）：
d = {"a": 1, "b": 2}
for k in d:
    print(k, d[k])

# =====================================================================
# 三、range()：生成一串整数
# =====================================================================
"""
range(start, stop, step)：生成从 start 到 stop（不含 stop）的整数序列。
  和切片一样"左闭右开"：包含 start，不含 stop。
"""
print(list(range(5)))          # [0, 1, 2, 3, 4]（只给 stop，默认从 0 开始，步长 1）
print(list(range(2, 5)))       # [2, 3, 4]
print(list(range(0, 10, 2)))   # [0, 2, 4, 6, 8]（步长 2）
print(list(range(5, 0, -1)))   # [5, 4, 3, 2, 1]（步长 -1，倒着数）

# for + range 配合：
for i in range(3):
    print("序号", i)

# 需要"下标"时，常见写法 range(len(list))，或用 enumerate（第 05 章见过）：
names = ["Tom", "Jerry"]
for i in range(len(names)):
    print(i, names[i])

# =====================================================================
# 四、break：提前跳出整个循环
# =====================================================================
for n in range(1, 100):
    if n > 3:
        break              # 一遇到 break，立刻结束整个 for
    print(n)               # 只打印 1 2 3

# 常见用法：找第一个满足条件的元素就停止
nums = [10, 20, 30, 5, 40]
for x in nums:
    if x % 2 == 0:
        print("找到第一个偶数：", x)
        break

# =====================================================================
# 五、continue：跳过本轮，继续下一轮
# =====================================================================
for n in range(1, 6):
    if n == 3:
        continue           # 跳过 n==3 这一轮，不执行下面的 print
    print("本轮", n)       # 打印 1 2 4 5（缺 3）

# =====================================================================
# 六、循环里的 else（冷门但要知道）
# =====================================================================
"""
for/while 也能接一个 else：当循环"正常结束"（没被 break 打断）时，
  才执行 else 块。若被 break 打断，则跳过 else。
"""
for n in range(3):
    print(n)
else:
    print("循环正常结束，没有 break")

for n in range(5):
    if n == 3:
        break
else:
    print("这行不会打印，因为被 break 打断了")

"""
【易混点】循环的 else 不是"失败才执行"，恰恰相反，是"没被 break 才执行"。
  它有个经典用途：在 for 里找元素，找不到时走 else。
"""
def has_even(arr):      # def 定义函数，第 12 章详解；这里先看逻辑
    for x in arr:
        if x % 2 == 0:
            break
    else:
        return False    # 没找到偶数（循环没 break）
    return True
print(has_even([1, 3, 5]))   # False
print(has_even([1, 3, 4]))   # True

# =====================================================================
# 七、循环嵌套：循环套循环（常见于二维遍历、乘法表）
# =====================================================================
for i in range(1, 4):
    for j in range(1, 4):
        print(i, j)          # 内层循环完整跑完，外层才走下一步

# 九九乘法表（经典练习）：
for i in range(1, 10):
    for j in range(1, i + 1):
        print(f"{j}×{i}={j * i}", end="\t")
    print()                  # 每行结束后换行

# =====================================================================
# 八、常见的几种循环写法套路
# =====================================================================
# 1) 遍历序列：for x in 序列
# 2) 带下标：  for i, x in enumerate(序列)
# 3) 计次：    for i in range(次数)
# 4) 条件循环：while 条件

# while True + break：读无限输入直到用户说"退出"（用列表模拟交互，input 见第18章）
print("while True 模式示例（模拟）：")
i = 0
while True:
    i += 1
    if i == 5:
        break
print("模拟循环结束，i =", i)

