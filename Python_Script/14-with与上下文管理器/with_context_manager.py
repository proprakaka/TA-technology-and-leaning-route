# -*- coding: utf-8 -*-
"""
第 14 章：with 与上下文管理器
===============================
很多资源（文件、网络连接、数据库连接、锁……）有个共同点：
  用之前要"打开/获取"，用完必须"关闭/释放"，否则会泄露资源。

朴素的写法容易忘关，于是 Python 提供了 with 语句，自动帮你善后。
================================================================
"""

# =====================================================================
# 一、先看"没有 with"的麻烦：手动打开、手动关闭
# =====================================================================
# 下面的文件操作在第 19 章详解，这里先关注"开/关"成对出现的结构。
f = open("temp_note.txt", "w", encoding="utf-8")   # 打开文件准备写
f.write("hello")                                     # 写内容
f.close()                                            # 手动关闭（容易忘！）

"""
如果 write 这步抛异常，close() 就不会被执行，文件句柄就泄露了。
with 语句能保证：无论块内是否报错，都会自动执行"清理动作"。
"""

# =====================================================================
# 二、with 的用法：打开后自动关闭
# =====================================================================
with open("temp_note.txt", "w", encoding="utf-8") as f:
    f.write("用 with 写入的内容\n")
    f.write("第二行\n")
# 缩进块结束，文件已自动关闭

# 读回来验证：
with open("temp_note.txt", "r", encoding="utf-8") as f:
    content = f.read()
print(content)

# =====================================================================
# 三、with 的底层原理：__enter__ 与 __exit__
# =====================================================================
"""
【原理】with 能作用的对象叫"上下文管理器（context manager）"，
  它内部定义了两个特殊方法：
    __enter__()：进入 with 块时执行，返回值赋给 as 后面的变量。
    __exit__() ：离开 with 块时执行（**无论是否发生异常都会执行**）。
  open("...") 返回的文件对象就是一个上下文管理器，其 __exit__ 里做了 close。

  下面自己写一个上下文管理器，把"进入/退出"打印出来看个明白：
"""
class MyContext:
    def __enter__(self):
        print(">>> 进入上下文")
        return "我是 as 后面拿到的东西"
    def __exit__(self, exc_type, exc_val, exc_tb):
        # 三个参数表示：异常类型、异常值、回溯对象；没有异常时都是 None
        print(">>> 退出上下文（无论是否异常都会到这一步）")
        return False     # 返回 False 表示"不吞掉异常"，异常继续向外抛

with MyContext() as value:
    print("块内拿到：", value)

"""
__exit__ 返回值约定：
  - 返回 False/None：异常照常向外抛（不吞）。
  - 返回 True：吞掉异常（假装没发生）。一般不这么做，除非你明确要抑制。
"""

# =====================================================================
# 四、一个实用的上下文管理器：计时器
# =====================================================================
import time

class Timer:
    def __enter__(self):
        self.start = time.time()
        return self
    def __exit__(self, *args):
        self.end = time.time()
        print(f"耗时：{self.end - self.start:.4f} 秒")

with Timer():
    total = sum(range(1000000))    # 计算这段代码花了多久

# =====================================================================
# 五、用 contextlib 把一个生成器函数变成上下文管理器（进阶）
# =====================================================================
from contextlib import contextmanager

@contextmanager          # 装饰器，第 15 章详解；这里知道它能"包装"函数即可
def managed_file(name):
    print("准备打开")
    f = open(name, "w", encoding="utf-8")
    try:
        yield f          # yield 之前 = __enter__；yield 之后 = __exit__
    finally:
        f.close()        # finally 一定会执行（第 20 章讲 finally）
        print("已关闭")

with managed_file("temp_note2.txt") as f:
    f.write("contextlib 版")

# =====================================================================
# 本章小结 + 预告
# =====================================================================
"""
小结：
  1. with 用于自动管理资源（进入/退出成对），即使报错也会善后。
  2. 原理是 __enter__ / __exit__ 两方法；上下文管理器 = 实现了这两个方法的对象。
  3. open() 返回的文件对象天然支持 with。
  4. contextlib.contextmanager 可把生成器函数变成上下文管理器。

预告：下一章讲**装饰器**——不改原函数代码、却能在函数前后加"额外动作"，
  它建立在前面闭包、高阶函数、@语法糖之上。
"""