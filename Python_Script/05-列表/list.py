# -*- coding: utf-8 -*-
"""
第 05 章：列表 list —— 第一个"可变"序列容器
=============================================
列表是 Python 里最常用的容器：把多个值按顺序装进一个"队伍"里。
它是"可变（mutable）"的：能增、删、改。
上一章字符串学的索引、切片、负下标，在列表里**全部通用**，因为列表也是序列。

本章重点：创建/索引/切片、增删改查、遍历、排序，以及最重要的
  【原地修改 vs 返回新对象】 的深刻区别。
=============================================
"""

# =====================================================================
# 一、创建列表
# =====================================================================
empty = []                    # 空列表
nums = [1, 2, 3, 4, 5]        # 数字列表
mixed = [1, "a", 3.14, True]  # 列表可以装不同类型（但一般建议同类型）
print(empty, nums, mixed)

# list() 可以把其他"可迭代对象"转成列表（"可迭代"概念见第 13 章）：
print(list("hello"))          # ['h', 'e', 'l', 'l', 'o']（把字符串拆成字符列表）
print(list(range(5)))         # [0, 1, 2, 3, 4]（range 见第 10 章）

# =====================================================================
# 二、索引与切片（和字符串完全一样，但切片得到的是"新列表"）
# =====================================================================
nums = [10, 20, 30, 40, 50]
print(nums[0])        # 10
print(nums[-1])       # 50（最后一个）
print(nums[1:4])      # [20, 30, 40]（左闭右开）
print(nums[::-1])     # [50, 40, 30, 20, 10]（倒序，得到新列表）
print(nums[::2])      # [10, 30, 50]（步长 2）

# =====================================================================
# 三、增：往列表里加东西
# =====================================================================
fruits = ["apple", "banana"]
fruits.append("cherry")        # 在末尾追加一个
print(fruits)                  # ['apple', 'banana', 'cherry']

fruits.insert(1, "pear")       # 在指定下标 1 处插入
print(fruits)                  # ['apple', 'pear', 'banana', 'cherry']

fruits.extend(["grape", "mango"])  # 把另一个列表的元素逐个追加到末尾
print(fruits)

# =====================================================================
# 四、删：去掉元素
# =====================================================================
fruits2 = ["apple", "banana", "cherry", "banana"]
fruits2.remove("banana")       # 删除第一个值为 "banana" 的元素
print(fruits2)                 # ['apple', 'cherry', 'banana']

popped = fruits2.pop()         # 弹出（删除并返回）末尾元素
print(popped, fruits2)         # banana ['apple', 'cherry']

fruits2.pop(0)                 # 弹出指定下标元素
print(fruits2)                 # ['cherry']

# del 语句：按下标删除，也可删整段切片（关键字 del 在第 16 章再次详细讲）
nums2 = [1, 2, 3, 4, 5]
del nums2[1]
print(nums2)                   # [1, 3, 4, 5]
del nums2[1:3]
print(nums2)                   # [1, 5]

# =====================================================================
# 五、改与查
# =====================================================================
nums3 = [1, 2, 3]
nums3[0] = 100                 # 直接按下标改值
print(nums3)                   # [100, 2, 3]

nums3[1:3] = [200, 300, 400]   # 切片赋值：把一段替换成另一段（长度可以不同！）
print(nums3)                   # [100, 200, 300, 400]

print(100 in nums3)            # True（成员判断）
print(nums3[1])                # 查：按索引取值

# =====================================================================
# 六、遍历：逐个取出元素（for 循环在第 10 章详解，这里先看语法）
# =====================================================================
for item in nums3:             # item 依次等于每个元素
    print("元素：", item)      # 这里每个元素打印一行

# 同时拿到"下标"和"值"：用 enumerate
for idx, value in enumerate(["a", "b", "c"]):
    print(idx, value)          # 0 a / 1 b / 2 c

# 按长度遍历：用 range(len(...))
names = ["Tom", "Jerry", "Spike"]
for i in range(len(names)):
    print(i, names[i])

# =====================================================================
# 七、排序与反转
# =====================================================================
data = [3, 1, 4, 1, 5, 9, 2]
data.sort()                    # 原地排序（默认升序），修改原列表
print("sort 后：", data)

data2 = [3, 1, 2]
sorted_data = sorted(data2)     # 返回新列表，不改原列表
print("sorted 结果：", sorted_data, "原列表：", data2)

data3 = [1, 2, 3]
data3.reverse()                 # 原地反转
print("reverse 后：", data3)

"""
【易混点】sort() vs sorted() —— 这是"可变 vs 不可变思想"的典型代表：
  - list.sort()  : 原地修改原列表，返回 None。
  - sorted(list) : 返回一个新列表，原列表不变。
  同理：append/remove/reverse 都是"原地方法"，返回 None；
       切片、sorted、list() 等返回"新对象"。
  所以 `print(nums.sort())` 会打印 None！正确是先 sort 再 print 原列表。
"""

# =====================================================================
# 八、可变性带来的"深坑"：别名与浅拷贝（务必看懂！）
# =====================================================================
"""
【原理】列表是可变对象。多个变量指向同一个列表时，改一个，另一个也"变"了。
  因为这两个变量只是同一个列表对象的两个"标签"（别名 alias）。
"""
a = [1, 2, 3]
b = a                  # b 和 a 指向同一个列表对象（不是复制！）
b.append(99)
print(a)               # [1, 2, 3, 99]——改 b，a 也变了！

"""
  想真正"复制一份"，浅拷贝用 [:] 或 .copy()：
"""
c = a[:]               # 切片得到新列表（浅拷贝）
c.append(100)
print("a =", a, " c =", c)     # c 变了，a 没变

"""
【易错点】"浅拷贝"只复制最外层。如果列表里还套列表（嵌套列表），
  内层仍然是共享的，改内层还会互相影响。想要完全独立要用"深拷贝"，
  见第 16 章 copy.deepcopy。
"""
outer = [[1, 2], [3, 4]]
shallow = outer[:]            # 浅拷贝：外层是新的，内层还是共享的
shallow[0].append(999)
print(outer)                  # [[1, 2, 999], [3, 4]]——内层被"连坐"了！

# =====================================================================
# 九、列表推导式（预告：第 11 章完整讲）
# =====================================================================
"""
一行代码造出列表：把 for 循环和表达式压缩成一行（推导式在第 11 章详解）。
  这里先混个脸熟： [对每个元素的处理 for 元素 in 可迭代对象]
"""
squares = [x * x for x in range(6)]
print(squares)                # [0, 1, 4, 9, 16, 25]

# =====================================================================
# 本章小结 + 预告
# =====================================================================
"""
小结：
  1. 列表是可变的序列：能用索引/切片，能增删改查。
  2. append/insert/extend 增；remove/pop/del 删；下标/切片赋值改。
  3. 原地方法（sort/reverse/append...）返回 None、改原列表；
     sorted/切片 返回新对象。
  4. 赋值只是加标签（别名），复制要用 [:] / .copy()（仍是浅拷贝）。

预告：下一章见"不能改的列表"——元组 tuple，以及它和列表到底怎么选。
"""