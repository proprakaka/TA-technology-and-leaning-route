# =====================================================================
# 一、标识符（identifier）：给变量、函数、类起的名字
# =====================================================================
"""
【原理】为什么需要"名字"？
  程序要处理数据。数据放在内存里，为了之后能再次找到它，我们给它贴一个
  标签、起一个名字——这个名字就叫"标识符"。想象成给储物柜贴编号：
  你把东西（值）放进柜子，并在柜门上写个名字，下次喊这个名字就能拿到。

  在 Python 里，"把值存起来并起名字"的写法就是赋值语句：
      名字 = 值
  这里的 = 不是"相等"，而是"把右边的值交给左边这个名字"，见第 03 章。

  Python 对标识符的硬性规定：
    1. 第一个字符必须是 字母 或 下划线 _。
    2. 其余部分只能是 字母、数字、下划线（不能有空格、连字符、$ 等）。
    3. 大小写敏感：count 和 Count 是两个不同的名字。
    4. 不能用关键字（见下一节）。
    5. 长度无硬性上限，但建议简短清晰。
"""
age = 25                 # 数字，变量名小写
user_name = "Alice"      # 多个单词用下划线连接（推荐：蛇形命名 snake_case）
_total = 100             # 下划线开头，通常表示"内部使用/私有"的约定，见第 22 章
MAX_SIZE = 1024          # 全大写，通常表示"常量"（不打算改的值，Python 里是约定）

print(age, user_name, _total, MAX_SIZE)

# Python 3 允许用中文等 Unicode 字符做标识符（合法但一般不建议，可读性/通用性差）：
姓名 = "张三"
π = 3.14159
print(姓名, π)

"""
【易错点】下面这些是"非法标识符"，直接复制运行会报语法错误。这里用注释列出，不要运行：
   2nd_place = "silver"   # 错：数字不能开头
   user-name = "Bob"      # 错：连字符不是合法字符
   class = "Math"         # 错：class 是关键字
   $price = 9.99          # 错：$ 不是合法字符
   我的 名字 = "张三"      # 错：中间有空格
"""

