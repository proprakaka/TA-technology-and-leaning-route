# 二、关键字（keyword）：被语言占用的保留字
# =====================================================================
"""
关键字是 Python 自己先占用的词，每个都有固定用途（if 判断、for 循环、
def 定义函数、class 定义类……），**不能拿来当变量名**。

用标准库 keyword 模块可以打印出当前版本的全部关键字：
"""
import keyword
