# =====================================================================
# 三、缩进与代码块：Python 最独特的规矩
# =====================================================================
"""
【原理】Python 不用大括号 {} 来圈定"一段代码属于哪个结构"，
  而是用**缩进**（行首的空格）来表达"这些行属于同一个代码块"。

  别的语言（如 C/Java）：
      if (x > 0) {         <- 大括号圈定块
          ...
      }

  Python：
      if x > 0:            <- 冒号表示"下面要开始一个代码块"
          ...              <- 缩进的行，属于这个 if
          ...
      ...                  <- 顶格的行，不属于这个 if

  规则核心：
    1. 同一个代码块里的语句，缩进必须**完全一致**（空格数量相同）。
    2. 缩进通常用 4 个空格（强烈推荐），也可以用 Tab，但**别混用**。
    3. 冒号 : 后面换行，下一行就要开始缩进。
"""
# 正确示例（一个 if，下面两行属于它）：
x = 10
if x > 0:                 # 冒号结尾，声明一个块开始
    print("x 是正数")     # 缩进 4 空格，属于这个 if 块
    print("这句话也属于 if 块")
print("这句话在最外层，不属于 if，永远会执行")

# 用代码演示两个不同的"块"如何区分（if/else 在第 09 章详解，这里只看缩进）：
y = -1
if y > 0:
    print("y 是正数")
else:
    print("y 不是正数")

"""
【易错点】缩进不一致会直接报 IndentationError，例如下面这行（不要取消注释）：
   if True:
       print("A")
      print("B")   # 这行比上一行少缩进，报错：
                   # IndentationError: unindent does not match any outer indentation level

【易混点】"空行"和"缩进"是两回事：
   - 缩进是语法的一部分，错了会报错。
   - 空行不是语法，只是两个功能段落之间的留白，为了让代码好读，可有可无。
"""

# =====================================================================
# 四、注释：不参与执行的说明文字
# =====================================================================
"""
注释是写给"看代码的人"看的，解释器会直接跳过它。
  - 单行注释：用 #
  - 多行注释：用三引号 '''...''' 或 \"\"\"...\"\"\"（严格说它是"多行字符串"，
    但位置合适时被当作注释用，见第 04 章字符串）
"""
# 这是单行注释
print("注释不影响运行")   # 行尾也可以加注释

'''
这是多行注释的第一行
这是第二行
'''
"""
这也是多行注释的常见写法
"""
print("上面两种都只是说明文字，不会输出")

# 注释还有个重要用法：给"还不存在的功能"占位，或临时关掉某行代码（调试常用）
# print("这行被注释掉了，不会执行")

# =====================================================================
# 五、多行语句：一行写不下怎么办
# =====================================================================
"""
Python 一般一行写一条语句。语句太长时有两种"续行"办法：
  办法 A：行尾加反斜杠 \ ，表示"下一行接着我"。
  办法 B：在 ()、[]、{} 内部，直接换行即可，不需要反斜杠。
"""
# 办法 A：反斜杠续行
total = 1 + \
        2 + \
        3
print("反斜杠续行结果：", total)   # 6

# 办法 B：括号内自由换行（列表 [] 到第 05 章详解，这里只看换行规则）
items = ['item_one', 'item_two', 'item_three',
         'item_four', 'item_five']
print("括号内换行：", items)

# =====================================================================
# 六、同一行写多条语句：用分号分隔（不推荐）
# =====================================================================
"""
Python 允许用分号 ; 把多条短语句挤到一行，但会牺牲可读性，一般不要用。
"""
a = 1; b = 2; print("同一行三条语句：", a + b)   # 能跑，但不建议

