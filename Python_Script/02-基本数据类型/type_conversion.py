# 获取输入示例：普通教程常在这里用 input()。为保持"可直接运行、无需交互"，
# 我们用字符串变量模拟输入。input() 本身在第 18 章详解。
user_input = "123"          # 注意：这是**字符串** "123"，不是数字 123
print(type(user_input))     # <class 'str'>

# =====================================================================
# 一、为什么需要类型转换
# =====================================================================
"""
【原理】不同类型之间不能直接做某些运算，否则报 TypeError。
  例如："123"（字符串）+ 456（整数）——一个是文字，一个是数字，
  Python 不知道该怎么做，直接报错。

  下面这行会报错，所以注释掉，不运行：
      result = "123" + 456    # TypeError: can only concatenate str ...
  想让它工作，就要先把字符串"123"转成整数 123，再相加。
"""

# =====================================================================
# 二、常用转换函数：int() / float() / str() / bool()
# =====================================================================
# int(x)：把 x 转成整数（能转的数字字符串、浮点数都可以）
print(int("123"))        # 123（字符串 -> 整数）
print(int(3.99))         # 3 ！注意：直接截断小数部分，不是四舍五入
print(int(True))         # 1（bool 转 int）

# float(x)：把 x 转成浮点数
print(float("3.14"))     # 3.14
print(float(10))         # 10.0
print(float("123"))      # 123.0

# str(x)：把 x 转成字符串（几乎任何类型都能转，常用于拼接输出）
print(str(123))          # '123'（现在是字符串）
print("数字 " + str(456))  # 用 str 后才能和字符串用 + 拼接

# bool(x)：把 x 转成布尔（按"真值"规则，见下方【原理】）
print(bool(1), bool(0))              # True False
print(bool("hello"), bool(""))       # True False（非空字符串为真）
print(bool(123), bool(None))         # True False

"""
【原理】"真值"判定：什么东西被当成 True，什么被当成 False？
  以下值在布尔上下文中被视为 False（其余一般都算 True）：
    - 数字 0（0、0.0、0j）
    - 空字符串 ""
    - 空列表 []、空元组 ()、空字典 {}、空集合 set()
    - None
  这条规则是后面 if / while 判断的基石（第 09、10 章）。
"""

# =====================================================================
# 三、能把什么字符串转成数字？（转不了会怎样）
# =====================================================================
print(int("  456  "))    # 前后有空格也能转，Python 会忽略两端的空白
# print(int("12.5"))     # 报错：int() 不能直接吃带小数点的字符串
# print(int("abc"))      # 报错：字母字符串无法转成整数
# print(int("12abc"))    # 报错：混着字母也不行

"""
【易错点】int 和 float 对字符串的要求不同：
  - int("12.5") 会报 ValueError，因为整数里不该有小数点。
  - 但 int(3.9) 合法（浮点数对象可转），结果是 3。
  想要"四舍五入"，得用 round()（见第 03 章内置函数部分）。

【原理】转换失败其实是在"抛异常"（raise an exception），
  程序会中断并给出 ValueError 之类的错误。异常与 try/except 在第 20 章详解。
"""

# 稳妥地处理"可能转不了"的输入——留个伏笔，正式写法见第 20 章：
text = "abc"
if text.isdigit():              # .isdigit() 判断字符串是否全是数字，见第 04 章
    number = int(text)
else:
    number = None
print("转换结果：", number)     # None

# =====================================================================
# 四、进制与整数 -> 字符串的进阶写法
# =====================================================================
# bin/oct/hex：把整数转成"二进制/八进制/十六进制"的字符串形式
print(bin(10))      # '0b1010'
print(oct(10))      # '0o12'
print(hex(10))      # '0xa'

# int(字符串, 基数)：指定进制把字符串解析成整数
print(int("1010", 2))     # 把"1010"当二进制解析，得到 10
print(int("1f", 16))      # 把"1f"当十六进制解析，得到 31

# =====================================================================
# 五、隐式转换：Python 有时会自动帮你转
# =====================================================================
"""
【原理】整数 + 浮点数 → Python 自动把 int 升级为 float 再算，得到 float。
  这叫"隐式类型转换"（implicit conversion）或"数值提升"。
  但 Python **不会**自动把字符串转成数字（显式才安全）。
"""
print(1 + 2.0)      # 3.0：int 1 被自动转成 float 1.0
print(type(1 + 2.0))  # <class 'float'>

