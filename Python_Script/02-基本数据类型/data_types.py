"""
第 02 章：基本数据类型（上）—— 变量、整数、浮点数、布尔、复数
================================================================
上一章我们学过：用 `名字 = 值` 把数据存起来。这一章回答两个问题：
    1. 数据有多少种"类型"？为什么计算机要区分类型？
    2. `age = 25` 这行代码，计算机在内存里到底做了什么？

本章先讲清楚"变量"和"类型"的最底层原理，再逐个认识 4 个数字类型。
================================================================
"""

# =====================================================================
# 一、变量与内存：`age = 25` 的真相
# =====================================================================
"""
【原理】变量（variable）不是"装着值的盒子"，而是一个"指向内存的标签"。
  当你写：
      age = 25
  计算机分三步做：
      1. 在内存里找块空地，把数字 25 存进去（25 是一个 int 对象）。
      2. 记住这块地的"门牌号"（内存地址，address）。
      3. 把名字 age 和这个门牌号绑定（说 age 指向这块内存）。

  所以更准确的说法是：age 是一个引用（reference），指向"值为 25 的对象"。

  下面用内置函数 id() 看一眼对象的"门牌号"（内存地址）：
"""
age = 25
print("age 的值：", age)
print("age 指向的对象内存地址：", id(age))

# 重新赋值会怎样？age 不再指向原来的 25，而是指向一个新的对象：
age = 26
print("重新赋值后：", age, "新地址：", id(age))
"""
  注意：原来的 25 那个对象若没人引用，会被 Python 的"垃圾回收(GC)"自动清理。
  你不需要手动释放内存，这是 Python 的一大便利。
  （"垃圾回收"会在第 22 章面向对象语境下再次提到。）
"""

# =====================================================================
# 二、为什么计算机要区分"类型"？
# =====================================================================
"""
【原理】类型（type）告诉计算机：这块内存里的数据该怎么解释、能做哪些运算。
  同样一个二进制串，解释成"整数"还是"文字"，含义完全不同。
  类型决定了：
    - 它占用多少内存（int 和 float 存法不同）
    - 能做哪些操作（数字能 +，字符串能"拼接 +"，但意义不同）
    - 运算结果是什么

  用 type() 可以查任何数据的类型：
"""
print(type(25))        # <class 'int'>
print(type(3.14))      # <class 'float'>
print(type(True))      # <class 'bool'>
print(type("abc"))     # <class 'str'>
print(type(None))      # <class 'NoneType'>

# =====================================================================
# 三、整数 int
# =====================================================================
"""
整数（int）：不带小数点的数。Python 3 的 int 没有大小上限（只受内存限制），
  不再像 Python 2 那样有单独的 long 长整型。
"""
a = 10
b = -3
big = 123456789012345678901234567890   # 非常大的整数也直接支持
print(a, b, big)

# int 还能用其他进制表示（底层都是同一个整数，只是写法不同）：
print(0b101)     # 二进制 0b 开头，等于 5
print(0o17)      # 八进制 0o 开头，等于 15
print(0x1F)      # 十六进制 0x 开头，等于 31
"""
【易混点】这些 0b/0o/0x 只是"写代码时表示整数"的语法糖，存到内存里都是
  同一个整数。print 出来默认还是十进制。
"""

# =====================================================================
# 四、浮点数 float
# =====================================================================
"""
浮点数（float）：带小数点、或用科学计数法表示的数。对应数学里的"实数"。
  注意：计算机里的 float 是"二进制近似"存储，会有精度问题（见下方易错点）。
"""
pi = 3.14159
huge = 1.5e10        # 科学计数法：1.5 × 10^10
small = 3e-2         # 3 × 10^-2，即 0.03
print(pi, huge, small)

"""
【易错点】浮点数精度：0.1 + 0.2 不一定等于 0.3！
  原因（底层原理）：十进制小数 0.1 在二进制里是无限循环小数，计算机只能用
  有限位数近似存储，累加时误差暴露出来。
"""
print(0.1 + 0.2)              # 结果是 0.30000000000000004，不是精确 0.3
print(0.1 + 0.2 == 0.3)       # False！比较浮点相等要小心

# 处理办法（用到模块和函数，先用起来，第 17 章详解 import）：
import math
print(math.isclose(0.1 + 0.2, 0.3))   # True：用 isclose 判断"足够接近"

# =====================================================================
# 五、布尔 bool
# =====================================================================
"""
布尔（bool）：只有两个值 True（真）和 False（假）。用来回答"是/否"。
  bool 本质是 int 的子类型：True == 1，False == 0。
"""
t = True
f = False
print(t, f)
print(True == 1, False == 0)      # 都 True，说明 bool 背后就是 1 和 0

"""
【易错点】True/False 首字母必须大写；true/false 会报错（Python 大小写敏感）。
【原理】布尔值从哪来？来自"比较运算"和"逻辑运算"的结果，见第 03 章。
  例如 3 > 2 的结果就是 True。
"""
print(3 > 2)      # True
print(3 < 2)      # False

# =====================================================================
# 六、复数 complex
# =====================================================================
"""
复数（complex）：形式为 a + bj，a 是实部，b 是虚部，j 是虚数单位。
  （数学书上常用 i 表示虚数单位，Python 用 j。）
"""
c1 = 1 + 2j
c2 = 1.1 + 2.2j
print(c1, c2)
print("实部：", c1.real, "虚部：", c1.imag)  # .real 和 .imag 是复数的属性
print("复数相加：", c1 + c2)

# =====================================================================
# 七、特殊值 None
# =====================================================================
"""
None 表示"空/没有值"，类型是 NoneType，它既不是 0、也不是空字符串、
  也不是 False。常用于表示"某个变量还没有被赋值意义"。
  （在函数一章会常见：函数不写 return 时默认返回 None，见第 12 章。）
"""
nothing = None
print(nothing, type(nothing))
print(None == 0, None == "", None == False)   # 全是 False，None 只等于 None

# =====================================================================
# 本章小结 + 预告
# =====================================================================
"""
小结：
  1. 变量是"指向内存对象的标签"，赋值 = 绑定新对象。
  2. 类型决定了数据如何被解释、能做哪些运算。
  3. 四个数字类型：int、float、bool（=1/0）、complex；另有 None。
  4. 浮点数有精度误差，比较相等用 math.isclose。

预告：下一章讲这些类型之间如何互相转换（int("123")、float、str 等），
  以及转换失败会怎样——引出"类型转换"和"异常"的伏笔。
"""