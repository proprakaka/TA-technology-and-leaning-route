# -*- coding: utf-8 -*-
"""
第 11 章：推导式（comprehension）
==================================
推导式 = 把"for 循环 + 生成一个新容器"压缩成一行的高效写法。
三种：列表推导式、字典推导式、集合推导式。（元组没有推导式，见底部说明）

语法骨架：
  列表：[表达式 for 元素 in 可迭代对象 if 条件]
  字典：{键表达式: 值表达式 for 元素 in 可迭代对象 if 条件}
  集合：{表达式 for 元素 in 可迭代对象 if 条件}

它和前面第 10 章循环是等价关系——先理解循环，再"翻译"成推导式。
================================================================
"""

# =====================================================================
# 一、先看等价性：循环 vs 推导式
# =====================================================================
# 用循环造列表 [0, 1, 4, 9, 16]
squares_loop = []
for x in range(5):
    squares_loop.append(x * x)
print("循环版：", squares_loop)

# 用推导式，一行：
squares_comp = [x * x for x in range(5)]
print("推导式版：", squares_comp)

"""
【原理】[x*x for x in range(5)] 的读法：
  从左到右读："对 range(5) 里的每个 x，计算 x*x，装进列表"。
  对比循环，推导式把"做什么（x*x）"放最前，"从哪来（for x ...）"放后面。
"""

# =====================================================================
# 二、加 if 条件过滤
# =====================================================================
evens = [x for x in range(10) if x % 2 == 0]
print("偶数：", evens)          # [0, 2, 4, 6, 8]

# 等价循环：
evens_loop = []
for x in range(10):
    if x % 2 == 0:
        evens_loop.append(x)
print(evens_loop)

# =====================================================================
# 三、对元素做处理（调用函数、方法）
# =====================================================================
words = ["hello", "world", "python"]
upper = [w.upper() for w in words]
print(upper)                   # ['HELLO', 'WORLD', 'PYTHON']

lengths = [len(w) for w in words]
print(lengths)                 # [5, 5, 6]

# =====================================================================
# 四、字典推导式
# =====================================================================
squares_dict = {x: x * x for x in range(5)}
print(squares_dict)            # {0:0, 1:1, 2:4, 3:9, 4:16}

# 反转字典的键和值：
d = {"a": 1, "b": 2, "c": 3}
reversed_d = {v: k for k, v in d.items()}
print(reversed_d)             # {1: 'a', 2: 'b', 3: 'c'}

# =====================================================================
# 五、集合推导式
# =====================================================================
squares_set = {x * x for x in range(5)}
print(squares_set)            # {0, 1, 4, 9, 16}

# 常见：把一个列表的重复去掉再“处理”
evens_set = {x for x in [1, 2, 2, 3, 4] if x % 2 == 0}
print(evens_set)              # {2, 4}

# =====================================================================
# 六、嵌套推导式（进阶，可读性会下降，慎用）
# =====================================================================
# 把一个二维列表"拍平"成一维：
matrix = [[1, 2, 3], [4, 5, 6], [7, 8, 9]]
flat = [num for row in matrix for num in row]
print(flat)                   # [1,2,3,4,5,6,7,8,9]

# 等价于：
flat_loop = []
for row in matrix:
    for num in row:
        flat_loop.append(num)
print(flat_loop)

"""
【易错点】嵌套推导式的顺序：写在前面的 for 是"外层"，与直觉可能相反：
  [num for row in matrix for num in row]
      先写外层 row，再写内层 num。
  嵌套层一到两层即可，超过两层强烈建议改回普通循环，可读性更重要。
"""

# =====================================================================
# 七、有没有"元组推导式"？
# =====================================================================
"""
【易错点】没有元组推导式！
  (x*x for x in range(5)) 这个东西不是元组，而是一个"生成器表达式"
  (generator expression)，它懒加载、逐个产出，取值要用 next 或包 list。
  它在第 13 章"生成器"里详解，这里先埋个印象即可。
"""
gen = (x * x for x in range(5))
print(gen)                     # <generator object ...>，不是元组！
print(list(gen))               # [0, 1, 4, 9, 16]（可转成列表再一次性看）

# =====================================================================
# 本章小结 + 预告
# =====================================================================
"""
小结：
  1. 推导式是"循环 + 过滤 + 构建新容器"的一行写法，等价于循环。
  2. 三种：列表 [..]、字典 {k:v ..}、集合 {..}；没有元组推导式。
  3. 加 if 可过滤；可嵌套但别过深。
  4. (x*x for x ...) 是生成器表达式，不是元组（第 13 章详解）。

预告：下一章讲**函数**——把一段逻辑打包、命名、复用。这是编程从
  "写脚本"走向"组织代码"的分水岭。
"""