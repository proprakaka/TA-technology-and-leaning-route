# -*- coding: utf-8 -*-
"""
第 12 章：函数（上）—— def、参数、返回值、作用域初探
========================================================
函数（function）= 把一段可复用的逻辑打包，起个名字，需要时"调用"它。
好处：一次定义，反复使用；改一处，处处生效；逻辑清晰。

回顾：第 00 章我们就见过内置函数 print()。这一章学"自己造函数"。
================================================================
"""

# =====================================================================
# 一、定义与调用
# =====================================================================
def greet():                 # def 关键字 + 函数名 + 圆括号 + 冒号
    print("你好！")          # 函数体（缩进块）

greet()                      # 调用：函数名 + 圆括号，会执行函数体
greet()                      # 可多次调用

# =====================================================================
# 二、参数：把数据传进函数
# =====================================================================
def add(a, b):               # a、b 是"形参（parameter）"，接收调用时给的值
    result = a + b
    print("和是", result)

add(3, 5)                    # 3、5 是"实参（argument）"，传给 a 和 b
add(10, 20)

# =====================================================================
# 三、返回值：把结果交还给调用方
# =====================================================================
"""
【原理】函数可以"返回"一个结果给调用它的人。用 return 语句：
  1. 立刻结束函数。
  2. 把 return 后面的值"交回去"，供调用处继续使用。
  如果不写 return 或只写 return，则默认返回 None。
"""
def add2(a, b):
    return a + b            # 返回 a+b，函数结束

total = add2(3, 4)         # 用变量接住返回值
print(total)               # 7

# 返回 None 的例子：
def no_return():
    x = 1                  # 只赋值，没有 return

r = no_return()
print(r)                   # None

# =====================================================================
# 四、位置参数与关键字参数
# =====================================================================
def introduce(name, age):
    print(f"我叫 {name}，{age} 岁")

introduce("小明", 20)          # 位置参数：按顺序对应
introduce(age=18, name="小红") # 关键字参数：按名字传，顺序无所谓
introduce("小刚", age=22)      # 位置在前，关键字在后（混合时位置参数必须在关键字参数之前）

# =====================================================================
# 五、默认参数
# =====================================================================
def power(base, exponent=2):   # exponent 有默认值 2
    return base ** exponent

print(power(3))               # 9（省略 exponent，用默认值 2）
print(power(3, 3))            # 27（传入则覆盖默认值）

"""
【易错点·重要】默认参数的值在"函数定义时"就被创建一次，之后复用同一个对象。
  若默认值是可变的（如列表），可能出现"意外共享"的坑：
"""
def add_item(item, bag=[]):    # 危险示例！默认参数是可变列表
    bag.append(item)
    return bag

print(add_item(1))            # [1]
print(add_item(2))            # [1, 2] ！第二次调用还带着上次的结果
print(add_item(3))            # [1, 2, 3]

# 正确写法：默认值用 None，函数内部再创建新列表
def add_item_fixed(item, bag=None):
    if bag is None:
        bag = []
    bag.append(item)
    return bag

print(add_item_fixed(1))      # [1]
print(add_item_fixed(2))      # [2]（每次都是新列表）
print(add_item_fixed(3))      # [3]

# =====================================================================
# 六、可变参数 *args 和 **kwargs（收集任意多个参数）
# =====================================================================
"""
*args：把任意多个"位置参数"收成一个元组。
**kwargs：把任意多个"关键字参数"收成一个字典。
"""
def sum_all(*args):
    total = 0
    for n in args:
        total += n
    return total

print(sum_all(1, 2, 3))          # 6
print(sum_all(1, 2, 3, 4, 5))    # 15（参数个数不限）

def show_info(**kwargs):
    for k, v in kwargs.items():
        print(f"{k} = {v}")

show_info(name="小明", age=20, city="北京")

# 解包反向使用：把列表/元组拆开传给函数
def multiply(a, b, c):
    return a * b * c

nums = [2, 3, 4]
print(multiply(*nums))         # 等价 multiply(2, 3, 4)

# =====================================================================
# 七、作用域初探：函数内外的变量（第 21 章完整讲）
# =====================================================================
"""
变量在函数内部定义的，是"局部变量"，函数外访问不到；
函数外定义的是"全局变量"，函数内可以读，但要改需用 global 声明。
"""
global_var = 100

def demo():
    local_var = 10            # 局部变量，只能在这个函数内用
    print("函数内能读到全局变量：", global_var)
    print("局部变量：", local_var)

demo()
# print(local_var)            # 报错！函数外访问不到局部变量

# 函数内直接"赋值"同名变量，默认是创建新的局部变量，而不是改全局：
x = 5
def change():
    x = 10        # 这是新建的局部变量，不影响全局 x
change()
print("全局 x 仍是：", x)      # 5

def change_global():
    global x                  # 声明我要用全局变量 x
    x = 10
change_global()
print("用 global 后 x：", x)   # 10

