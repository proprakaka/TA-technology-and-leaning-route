# -*- coding: utf-8 -*-
"""
第 04 章：字符串（上）—— 是什么、怎么创建、索引与切片、不可变
================================================================
字符串（string，类型名 str）是一串字符，表示文字。
它是第一个"序列（sequence）"类型——序列就是"一堆元素按顺序排成一队"。
本章先把字符串这个最简单序列吃透，后面列表/元组会复用同一套思想。
================================================================
"""

# =====================================================================
# 一、创建字符串：单引号、双引号、三引号
# =====================================================================
s1 = '用单引号'
s2 = "用双引号"
print(s1, s2)
print(s1 == "用单引号")   # True：单引号和双引号完全等价

# 三引号用于"多行字符串"（能跨越多行，保留换行）：
paragraph = """第一行
第二行
第三行"""
print(paragraph)

# 引号里要包含引号怎么办？用不同引号，或用转义：
print("他说：'你好'")          # 外双内单
print('他说："你好"')          # 外单内双
print("他说：\"你好\"")         # 用反斜杠转义双引号（\ 的作用见下）

# Python 没有"字符(char)"类型：一个字符就是长度为 1 的字符串
single = "a"
print(len(single))         # 1  （len() 返回字符串长度）

# =====================================================================
# 二、转义字符与原始字符串
# =====================================================================
"""
【原理】转义字符：反斜杠 \ 后面的字符有特殊含义，用来表示"打不出来的字符"。
  常见：\n 换行，\t 制表符(Tab)，\\ 表示一个真正的反斜杠，\' 单引号，\" 双引号。
"""
print("第一行\n第二行")            # \n 处换行
print("列1\t列2")                  # \t 处插入 Tab 对齐
print("路径是 C:\\Users\\Tom")     # \\ 显示为一个反斜杠

# 原始字符串（raw string）：开头加 r，反斜杠不再转义，原样保留
print(r"第一行\n第二行")           # 输出字面的 \n，不换行
print(r"C:\Users\Tom")             # 写 Windows 路径很方便

"""
【易混点】普通字符串 vs 原始字符串：
  "C:\new"  →  \n 被当成换行，变成 C + 换行 + ew
  r"C:\new" →  原样 C:\new
  写路径、写正则表达式时常用 r 前缀。
"""

# =====================================================================
# 三、索引：从 0 开始的位置编号
# =====================================================================
"""
【原理】字符串里每个字符都有"下标（索引 index）"。
  Python 的索引从 0 开始，不是 1：
      字符:   P  y  t  h  o  n
      正索引: 0  1  2  3  4  5
      负索引: -6 -5 -4 -3 -2 -1   （负数从右往左数，最后一个字符是 -1）
"""
word = "Python"
print(word[0])      # 'P'（第 1 个）
print(word[5])      # 'n'（第 6 个）
print(word[-1])     # 'n'（最后一个）
print(word[-2])     # 'o'（倒数第二个）

# len() 得到长度，最后一个字符的"正索引"是 len-1：
print(len(word))            # 6
print(word[len(word) - 1])  # 'n'

"""
【易错点】越界：索引超出范围会报 IndexError，例如 word[6]（只有 0~5）。
  （异常处理的写法见第 20 章。）
"""

# =====================================================================
# 四、切片：取出一段连续的子串
# =====================================================================
"""
【原理】切片语法：str[start:end:step]
  - start：开始下标（包含）
  - end  ：结束下标（**不包含**）——取到 end-1 为止
  - step ：步长（每隔几个取一个，默认 1）

  记忆口诀："左闭右开"——包含左边界，不含右边界。
"""
s = "0123456789"
print(s[0:5])       # '01234'（下标 0~4，不含 5）
print(s[2:5])       # '234'
print(s[2:])        # '23456789'（省略 end，取到末尾）
print(s[:5])        # '01234'（省略 start，从开头取）
print(s[:])         # '0123456789'（都省略，整体拷贝）
print(s[::2])       # '02468'（步长 2，隔一个取一个）
print(s[::-1])      # '9876543210'（步长 -1，倒序！常用）

"""
【易混点】"左闭右开"是新手最容易踩的坑：
  s[2:5] 取的是下标 2、3、4 三个字符，不包括下标 5。
  它也带来一个优雅性质：s[:i] + s[i:] == s（在任意 i 处切开再拼回，仍完整）。

【原理】负索引在切片里也可用：
  s[-3:] 表示"从倒数第 3 个到末尾"。
"""
print(s[-3:])       # '789'（最后 3 个字符）

# =====================================================================
# 五、字符串是不可变的（不可修改）
# =====================================================================
"""
【原理】字符串一旦创建，内容就不能改。想"改"，只能造一个新字符串。
  下面这行会报错（TypeError），注释掉不运行：
      word[0] = 'J'   # TypeError: 'str' object does not support item assignment

  但你可以基于旧字符串拼接出新字符串：
"""
new_word = "J" + word[1:]      # 拼出 "Jython"
print(new_word)

"""
【原理】为什么不可变？—— 出于安全、性能和可哈希等设计考虑。
  "可哈希"这个词会在字典（第 07 章）与集合（第 08 章）里解释。
  不可变对象被多处引用时，不会出现"一方偷偷改了、另一方措手不及"的问题。
"""

# =====================================================================
# 六、字符串的运算：拼接与重复
# =====================================================================
print("this " + "is " + "string")      # 用 + 拼接
print("ha" * 3)                        # 用 * 重复 3 次
# print("abc" + 1)   # 报错！字符串不能和数字直接 +，要先 str(1)

# 字面量相邻会自动拼接（注意：必须是"字面量"，变量之间不行）：
print("this " "is " "string")

