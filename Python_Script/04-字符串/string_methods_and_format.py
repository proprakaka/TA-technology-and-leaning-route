# -*- coding: utf-8 -*-
"""
第 04 章：字符串（下）—— 常用方法 与 格式化输出
==================================================
继续字符串。这一节分两块：
  1. 字符串的常用"方法"（method）：查找、替换、拆分、大小写、去空白等。
  2. 格式化输出：把变量值漂亮地放进字符串里的三种写法。

先解释一个贯穿本节课的关键概念：方法。
【原理】"方法"就是"挂在某个对象上的函数"，调用格式是 `对象.方法名(...)`。
  字符串是 str 类型的对象，它自带一批方法，通过 `字符串.` 来调用。
  `word.upper()` 意思是：对 word 这个字符串对象，调用它的 upper 方法
  （返回一个全部大写的新字符串）。深入讲"对象/方法"在面向对象第 22 章。
================================================================
"""

s = "  Hello, Python World  "

# =====================================================================
# 一、常用方法（方法名直觉就能猜个大概）
# =====================================================================
print(s.upper())          # 全部转大写：'  HELLO, PYTHON WORLD  '
print(s.lower())          # 全部转小写
print(s.title())          # 每个单词首字母大写
print(s.strip())          # 去掉两端的空白（空格/换行/Tab）
print(s.lstrip())         # 只去左边空白
print(s.rstrip())         # 只去右边空白

print(s.find("Python"))   # 返回子串第一次出现的下标，找不到返回 -1
print(s.index("Python"))  # 同上，但找不到会抛 ValueError（不是 -1）
print(s.count("o"))       # 统计 o 出现几次

print(s.replace("World", "Python"))   # 把 World 替换成 Python（返回新串）
print(s.startswith("  Hello"))        # 是否以某前缀开头
print(s.endswith("World  "))          # 是否以某后缀结尾

print("a,b,c".split(","))     # 按 , 拆分，得到列表 ['a', 'b', 'c']
print("-".join(["a", "b", "c"]))  # 用 - 连接一个列表，得到 'a-b-c'

print("42".isdigit())         # 是否全是数字
print("abc123".isalpha())     # 是否全是字母（False，因为含数字）
print("   ".isspace())        # 是否全是空白

"""
【原理】字符串不可变，所以上面这些方法都**不修改原字符串**，
  而是返回一个新字符串。想保留结果，必须赋值给变量：
      s2 = s.upper()
  如果只写 s.upper() 而不接住返回值，结果就丢了。
  （这个"方法返回新对象 vs 原地修改对象"的区分，在列表第 05 章是重头戏。）
"""

# =====================================================================
# 二、格式化输出：三种写法
# =====================================================================
name = "小明"
age = 20
score = 92.5

# 写法 1：f-string（Python 3.6+，最推荐，最直观）
print(f"我叫 {name}，今年 {age} 岁，考了 {score} 分")
# 花括号里还能写表达式：
print(f"明年我就 {age + 1} 岁")
print(f"分数保留一位小数：{score:.1f}")    # :.1f 表示保留 1 位小数的浮点格式

# 写法 2：str.format()（Python 3 通用，占位符用 {}）
print("我叫 {}，今年 {} 岁".format(name, age))
print("我叫 {0}，今年 {1} 岁".format(name, age))   # 用下标指定顺序
print("分数：{0:.2f}".format(score))                # {:.2f} 保留 2 位小数

# 写法 3：% 老式格式化（沿用自 Python 2，现在不推荐但很常见）
print("我叫 %s，今年 %d 岁" % (name, age))          # %s 字符串，%d 整数
print("分数：%.1f" % score)                          # %.1f 保留 1 位小数

# 常用格式符速查：
pi = 3.1415926
print(f"保留2位：{pi:.2f}")      # 3.14
print(f"宽度10右对齐：|{pi:10.2f}|")   # 总宽 10，右对齐
print(f"宽度10左对齐：|{pi:<10.2f}|")  # < 左对齐
print(f"补零：{42:05d}")          # 00042（宽度5，用0补齐）
print(f"百分号：{0.25:.1%}")      # 25.0%

"""
【易混点】三种格式化写法选哪个？
  - 新代码：优先 f-string（简洁、可读、性能好）。
  - 看别人的老代码：可能遇到 .format() 和 %，会读即可。
  - 需要"模板先定、值后填"（如延迟填充）时用 .format()。
"""

# =====================================================================
# 三、字符串与编码：Unicode 与 UTF-8（浅尝）
# =====================================================================
"""
【原理】计算机只能存数字，那"字"怎么存？——靠"编码"给每个字符配一个编号。
  - Unicode：一个"字符表"，给全世界每个字符分配唯一编号（码点 code point）。
    例如汉字"中"的 Unicode 码点是 U+4E2D。
  - UTF-8：一种"编码方案"，把 Unicode 码点用字节（byte）表示出来。
    它是变长的：ASCII 字符用 1 字节，中文一般用 3 字节。

  Python 3 的 str 是"码点序列"（内部用 Unicode），
  而磁盘文件/网络传输时用"字节序列"（bytes），二者通过 encode/decode 转换。
"""
print(ord("中"))        # 20013（十进制码点，等于十六进制 4E2D）
print(hex(ord("中")))   # '0x4e2d'（十六进制码点）
print(chr(20013))       # '中'（码点转回字符）

text = "你好"
encoded = text.encode("utf-8")    # str -> bytes（编码）
print(encoded)                     # b'\xe4\xbd\xa0\xe5\xa5\xbd'
print(encoded.decode("utf-8"))     # bytes -> str（解码，还原）

"""
这个 encode/decode 会在"文件读写 + 二进制模式"（第 19 章）再次出现，
  到时候理解起来就顺了。
"""

