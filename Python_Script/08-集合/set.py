# -*- coding: utf-8 -*-
"""
第 08 章：集合 set —— 去重 + 集合运算
========================================
集合（set）像一个"去掉重复、且不讲究顺序"的口袋：装一堆元素，但
  1) 元素不会重复
  2) 元素顺序不确定
  3) 元素必须可哈希（不可变）——和字典的键要求一样

它最常用于：去重、判断交集/并集/差集。
================================================================
"""

# =====================================================================
# 一、创建集合
# =====================================================================
s1 = {1, 2, 3, 3, 2}          # 重复元素会自动被去掉
print(s1)                     # {1, 2, 3}（顺序可能不同）

# 空集合必须用 set()，不能用 {}（{} 是空字典！）
empty_set = set()
empty_dict = {}
print(type(empty_set), type(empty_dict))    # set 和 dict

# set() 从其他可迭代对象转集合：
print(set([1, 2, 2, 3]))      # {1, 2, 3}
print(set("hello"))           # {'h', 'e', 'l', 'o'}（字符去重，l 只有一个）

# =====================================================================
# 二、增删
# =====================================================================
s = {1, 2, 3}
s.add(4)                      # 加一个元素
print(s)
s.add(1)                      # 已存在，无变化（集合不去重就失去意义了）
print(s)

s.remove(2)                   # 删除元素；不存在会报 KeyError
print(s)
s.discard(99)                 # 删除元素；不存在也不报错（更安全）
print(s)

# =====================================================================
# 三、集合运算：交、并、差
# =====================================================================
A = {1, 2, 3, 4}
B = {3, 4, 5, 6}

print("交集 &：", A & B)          # {3, 4}（两者都有的）
print("并集 |：", A | B)          # {1,2,3,4,5,6}（合并去重）
print("差集 -：", A - B)          # {1, 2}（在 A 里但不在 B 里）
print("对称差 ^：", A ^ B)        # {1, 2, 5, 6}（只在一方出现的）

# 用方法也一样：
print(A.intersection(B))
print(A.union(B))
print(A.difference(B))

# 子集/超集判断：
print({1, 2}.issubset(A))     # True（{1,2} 是 A 的子集）
print(A.issuperset({1, 2}))   # True

# =====================================================================
# 四、集合的典型用途：给列表去重
# =====================================================================
items = [1, 2, 2, 3, 3, 3, 4]
unique = list(set(items))      # 转集合去重，再转回列表
print(unique)                  # [1, 2, 3, 4]（顺序可能变）

# 若想"去重且保持原顺序"（利用字典键去重，Python 3.7+ 有序）：
unique_ordered = list(dict.fromkeys(items))
print(unique_ordered)         # [1, 2, 3, 4]（保持首次出现顺序）

# =====================================================================
# 五、集合推导式（预告第 11 章）
# =====================================================================
evens = {x for x in range(10) if x % 2 == 0}
print(evens)                  # {0, 2, 4, 6, 8}

# =====================================================================
# 六、frozenset：不可变集合
# =====================================================================
"""
普通 set 是可变的，因此本身不可哈希、不能作字典键。
frozenset 是不可变集合，可哈希，能作键/放进另一个集合。
"""
fs = frozenset([1, 2, 3])
print(fs, type(fs))
# 可作为字典键：
d = {fs: "不可变集合当键"}
print(d[fs])

"""
【易错点】可变容器（list/set/dict/set 本身）都不能当集合元素或字典键；
  想"装进集合里的集合"，用 frozenset。
"""

# =====================================================================
# 本章小结 + 预告
# =====================================================================
"""
小结：
  1. 集合：无序、去重、元素可哈希；空集合用 set()。
  2. 交 & 并 | 差 - 对称差 ^；子集 issubset/issuperset。
  3. 去重常用 list(set(xs))；想保序用 dict.fromkeys。
  4. frozenset 是不可变集合。

预告：到这里，Python 的四大容器（列表/元组/字典/集合）齐了。
  下一章开始讲"控制流"：条件判断 if/elif/else，让程序学会"做选择"。
"""