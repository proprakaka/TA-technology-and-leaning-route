//=========================================================
// 第25章 C# 预处理指令 (Preprocessor Directives)
//=========================================================
//预处理指令是以 # 开头、在编译前由编译器处理的指令，不是普通代码。
//它们不以分号结尾。常用：条件编译(#if/#else)、区域折叠(#region)、告警(#warning)等。

//注意：#define 必须在文件最顶部（using 之前）出现，用来"定义编译符号"。
#define DEBUG_MODE      // 定义一个符号，供 #if 判断

using System;

namespace PreprocessorTeaching
{
    class Program
    {
        static void Main()
        {
            //-----------------------------------------------------
            // 1. 条件编译：#if / #elif / #else / #endif
            //    只有符号被 #define 定义，对应的分支才会被编译进程序。
            //-----------------------------------------------------
            #if DEBUG_MODE
                Console.WriteLine("当前处于【调试】模式");
            #else
                Console.WriteLine("当前处于【发布】模式");
            #endif

            //-----------------------------------------------------
            // 2. #warning 与 #error：编译时打印告警 / 产生错误。
            //    #error 会直接让编译失败。
            //-----------------------------------------------------
            #if DEBUG_MODE
                #warning 这段代码仅用于调试，发布前请移除
            #endif

            //-----------------------------------------------------
            // 3. #region / #endregion：把一段代码"折叠"起来，方便阅读。
            //    这在编辑器里会变成一个可折叠的块。
            //-----------------------------------------------------
            #region 辅助计算
            int a = 10;
            int b = 20;
            int sum = a + b;
            Console.WriteLine("sum = {0}", sum);
            #endregion

            //-----------------------------------------------------
            // 4. #line：控制编译器报告的行号（极少用，了解即可）。
            //-----------------------------------------------------
            //#line 200
            //Console.WriteLine("这行会假装在第 200 行");

            Console.ReadKey();
        }
    }
}

/*
【小结】
  · #define 定义符号、#undef 取消符号（须在 using 之前）；
  · #if #elif #else #endif 条件编译：按符号决定哪些代码参与编译；
  · #warning 提示告警，#error 制造编译错误；
  · #region / #endregion 折叠代码块，便于阅读。
*/