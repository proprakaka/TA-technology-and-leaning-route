【C# 是什么？】
C#（读作 "C Sharp"）是微软开发的一门现代、通用、面向对象的编程语言，
语法上借鉴了 C / C++ 的风格（大括号 {}、分号 ;），也吸收了 Java 的面向对象机制。

【C# 和 .NET 是什么关系？】
打个比方：如果把 C# 比作"驾驶技术"，那 .NET 就是"汽车和道路基础设施"。
你用 C# 写出的代码，需要运行在 .NET 这个平台上。
.NET 提供两样东西：
  1) 运行时（负责执行代码、自动管理内存——也就是"自动垃圾回收 GC"）；
  2) 海量的标准类库（现成的工具：读写文件、发网络请求、操作数据库……）。

【能用 C# 做什么？】
  - 桌面应用（Windows 办公软件、管理系统）
  - Web 后端（ASP.NET Core 高性能网站/接口）
  - 游戏开发（Unity 引擎，比如《王者荣耀》《原神》主要都是C#写的）
  - 移动应用（.NET MAUI 一套代码写 iOS/Android）
  - 云计算、人工智能（ML.NET 等）

【与其它语言的简单对比】
  - 比 C/C++：屏蔽了指针和手动内存管理，入门更简单，不需要过分考虑对内存的直接操作；
  - 比 Java：两者很像，但 C# 语言特性更现代（更早引入 Lambda、async/await 等）；
  - 比 Python：C# 是强类型语言，更适合大型、高性能工程，协作更易维护。

