//=========================================================
// 第10章 C# 判断（条件语句）
//=========================================================
//判断：根据条件是否成立，决定执行哪一段代码。
//主要有：if / if...else / if...else if...else、嵌套 if、switch、三元运算符。

using System;

namespace DecisionTeaching
{
    class Program
    {
        static void Main()
        {
            //-----------------------------------------------------
            // 1. if 语句：条件为 true 才执行大括号里的语句。
            //-----------------------------------------------------
            int a = 10;
            if (a < 20)
            {
                Console.WriteLine("a 小于 20");   // 10 < 20 成立，会执行
            }

            //-----------------------------------------------------
            // 2. if...else：条件成立走 if 分支，否则走 else 分支。
            //-----------------------------------------------------
            int b = 30;
            if (b < 20)
            {
                Console.WriteLine("b 小于 20");
            }
            else
            {
                Console.WriteLine("b 大于等于 20");   // 30 >= 20，走这里
            }

            //-----------------------------------------------------
            // 3. if...else if...else：多条件依次判断。
            //-----------------------------------------------------
            int score = 85;
            if (score >= 90)
            {
                Console.WriteLine("优秀");
            }
            else if (score >= 80)
            {
                Console.WriteLine("良好");            // 85 落在这里
            }
            else if (score >= 60)
            {
                Console.WriteLine("及格");
            }
            else
            {
                Console.WriteLine("不及格");
            }

            //-----------------------------------------------------
            // 4. 嵌套 if：一个 if 里面再套一个 if。
            //-----------------------------------------------------
            int c = 100;
            if (c == 100)
            {
                if (c > 50)                 // 内层 if
                {
                    Console.WriteLine("c 等于 100 且大于 50");
                }
            }

            //-----------------------------------------------------
            // 5. switch 语句：根据某个变量的“不同取值”跳转到对应分支。
            //    break 用于跳出整个 switch。
            //    default 表示“都不匹配时”的兜底分支。
            //-----------------------------------------------------
            char grade = 'B';
            switch (grade)
            {
                case 'A':
                    Console.WriteLine("很棒！");
                    break;
                case 'B':
                case 'C':                     // B 和 C 共用同一段逻辑
                    Console.WriteLine("做得不错");
                    break;
                case 'D':
                    Console.WriteLine("需要努力");
                    break;
                default:
                    Console.WriteLine("无效的等级");
                    break;
            }

            //-----------------------------------------------------
            // 6. 三元运算符 ?: （上章已见）—— if...else 的简洁写法。
            //    语法： 条件 ? 真值 : 假值
            //-----------------------------------------------------
            int age = 18;
            string result = age >= 18 ? "成年" : "未成年";
            Console.WriteLine("年龄 {0}，{1}", age, result);

            Console.ReadKey();
        }
    }
}

/*
【小结】
  · if / if-else / if-else if-else：最常用的条件判断；
  · 嵌套 if：判断里再判断；
  · switch：适合"一个变量、多个固定取值"的分支场景，记得每个 case 末尾写 break；
  · 三元运算符 ?:：单行、简单的二选一可用它。
*/