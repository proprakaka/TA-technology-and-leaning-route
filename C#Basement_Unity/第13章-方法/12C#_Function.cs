//=========================================================
// 第13章 C# 方法 (Methods)
//=========================================================
//“方法”就是一段有名字、可复用、可传入参数并返回结果的代码块。
//之前出现的 Console.WriteLine、r.Display()、GetArea() 都是方法。

using System;

namespace MethodsTeaching
{
    class Program
    {
        //-----------------------------------------------------
        // 定义一个方法的一般结构：
        //   访问修饰符 返回类型 方法名(参数列表) { 方法体 }
        //-----------------------------------------------------
        //返回 int 型结果；参数 (int num1, int num2) 是两个输入。
        static int Add(int num1, int num2)
        {
            int sum = num1 + num2;
            return sum;          // return：把结果返回给调用者，并结束方法
        }

        //-----------------------------------------------------
        // 递归：方法在自己的方法体里“调用自己”。
        // 经典例子：计算阶乘 n! = n × (n-1) × ... × 1
        //-----------------------------------------------------
        static int Factorial(int n)
        {
            if (n <= 1)
                return 1;                    // 递归的“终止条件”（没有它会无限递归）
            return n * Factorial(n - 1);     // 自己调用自己
        }

        //-----------------------------------------------------
        // 参数传递方式一：值传递（默认）
        //    方法内部对参数变量的修改，不会影响外部的原始变量。
        //-----------------------------------------------------
        static void ByValue(int x)
        {
            x = 100;     // 改的是"副本"
        }

        //-----------------------------------------------------
        // 参数传递方式二：引用传递（ref）
        //    传进去的是"变量的引用"，方法内修改会同步影响外部变量。
        //    调用时也要写 ref。
        //-----------------------------------------------------
        static void ByReference(ref int x)
        {
            x = 200;     // 会改变外部的变量
        }

        //-----------------------------------------------------
        // 参数传递方式三：输出参数（out）
        //    用来"把多个结果返回给调用者"。被 out 修饰的参数在方法内部必须赋值。
        //-----------------------------------------------------
        static void GetValues(out int x, out int y)
        {
            x = 10;      // out 参数必须在方法里赋值
            y = 20;
        }

        static void Main()
        {
            //调用普通有返回值的方法
            int result = Add(3, 5);
            Console.WriteLine("Add(3, 5) = {0}", result);

            //调用递归方法
            Console.WriteLine("5! = {0}", Factorial(5));

            //值传递：外部变量不会变
            int a = 1;
            ByValue(a);
            Console.WriteLine("值传递后 a = {0}（仍是 1）", a);

            //引用传递：外部变量会变
            int b = 1;
            ByReference(ref b);
            Console.WriteLine("引用传递后 b = {0}（变为 200）", b);

            //输出参数：一次拿到多个结果
            int outX, outY;
            GetValues(out outX, out outY);
            Console.WriteLine("out 参数：x={0}, y={1}", outX, outY);

            Console.ReadKey();
        }
    }
}

/*
【小结】
  · 方法 = 访问修饰符 + 返回类型(void 表示无返回) + 方法名 + (参数) + { 体 }；
  · return：返回结果并结束方法；
  · 递归：方法调用自身，必须有终止条件；
  · 参数传递：
       值传递（默认）——改副本，不影响外部；
       引用传递 ref  ——方法内改动同步到外部；
       输出参数 out   ——向调用者"吐出"多个结果。
*/